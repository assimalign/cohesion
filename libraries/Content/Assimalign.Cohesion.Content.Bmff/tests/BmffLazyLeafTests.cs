using System.IO;
using System.Threading;
using System.Threading.Tasks;

using Shouldly;
using Xunit;

namespace Assimalign.Cohesion.Content.Bmff.Tests;

public class BmffLazyLeafTests
{
    [Fact(DisplayName = "Cohesion Test [Content.Bmff] - Lazy leaf: ISO 14496-12 sparse payload and deferred cap")]
    public void Load_SparseProfileLeaf_DefersBufferLimitUntilRequested()
    {
        // Arrange
        using var source = new SparseMediaStream();
        var registry = BmffBoxRegistry.CreateBuilder().Register(BmffBoxType.MediaData, _ => new LazyProfileBox()).Build();

        // Act
        using var document = BmffDocument.Load(source, new BmffReaderOptions { MaxBufferedPayloadSize = 16 }, registry);
        var box = document.Boxes[0].ShouldBeOfType<LazyProfileBox>();

        // Assert
        box.IsLeaf.ShouldBeTrue();
        box.IsComposite.ShouldBeFalse();
        box.Payload.Length.ShouldBe(SparseMediaStream.MediaSize);
        source.BytesRead.ShouldBe(24);
        Should.Throw<ContentFormatException>(() => box.Materialize()).ErrorCode.ShouldBe(ContentFormatErrorCode.LimitExceeded);
    }

    [Fact(DisplayName = "Cohesion Test [Content.Bmff] - Lazy leaf: ISO 14496-12 borrowed bytes survive reader disposal and stream saves")]
    public async Task SaveAsync_ProfileLeafAboveCap_CopiesIdenticalBytes()
    {
        // Arrange: original box bytes generated by the fixture header writer.
        var bytes = BmffFixtures.Box("mdat", new byte[] { 1, 2, 3, 4, 5 });
        using var source = new MemoryStream(bytes);
        var registry = BmffBoxRegistry.CreateBuilder().Register(BmffBoxType.MediaData, _ => new LazyProfileBox()).Build();
        using var document = BmffDocument.Load(source, new BmffReaderOptions { MaxBufferedPayloadSize = 4 }, registry);
        using var output = new MemoryStream();
        using var forward = new ProbeStream(output, false);

        // Act
        await document.SaveAsync(forward, CancellationToken.None);

        // Assert
        output.ToArray().ShouldBe(bytes);
        Should.Throw<ContentFormatException>(() => ((LazyProfileBox)document.Boxes[0]).Materialize()).ErrorCode.ShouldBe(ContentFormatErrorCode.LimitExceeded);
    }

    [Fact(DisplayName = "Cohesion Test [Content.Bmff] - Lazy leaf: ISO 14496-12 bounded typed byte access")]
    public void ReadPayloadBytes_WithinCap_ReturnsOriginalPayload()
    {
        // Arrange
        using var source = new MemoryStream(BmffFixtures.Box("mdat", new byte[] { 9, 8 }));
        var registry = BmffBoxRegistry.CreateBuilder().Register(BmffBoxType.MediaData, _ => new LazyProfileBox()).Build();

        // Act
        using var document = BmffDocument.Load(source, new BmffReaderOptions { MaxBufferedPayloadSize = 2 }, registry);

        // Assert
        ((LazyProfileBox)document.Boxes[0]).Materialize().ShouldBe(new byte[] { 9, 8 });
    }
}
