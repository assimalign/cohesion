using System.Collections.Generic;
using System.Text;

using Shouldly;
using Xunit;

namespace Assimalign.Cohesion.Content.Binary.Tests;

public class BinaryContentReaderTests
{
    public static IEnumerable<object[]> Fields()
    {
        yield return ["Byte", 1];
        yield return ["SByte", 1];
        yield return ["UInt16BigEndian", 2];
        yield return ["Int16BigEndian", 2];
        yield return ["UInt32BigEndian", 4];
        yield return ["Int32BigEndian", 4];
        yield return ["UInt64BigEndian", 8];
        yield return ["Int64BigEndian", 8];
        yield return ["UInt16LittleEndian", 2];
        yield return ["Int16LittleEndian", 2];
        yield return ["UInt32LittleEndian", 4];
        yield return ["Int32LittleEndian", 4];
        yield return ["UInt64LittleEndian", 8];
        yield return ["Int64LittleEndian", 8];
        yield return ["UInt24BigEndian", 3];
        yield return ["SingleBigEndian", 4];
        yield return ["DoubleBigEndian", 8];
        yield return ["FourCC", 4];
        yield return ["FixedPoint16x16", 4];
        yield return ["UnsignedFixedPoint16x16", 4];
        yield return ["FixedPoint8x8", 2];
        yield return ["FixedPoint2x30", 4];
        foreach (var method in new[] { "Bytes", "Exactly", "Skip", "Utf8String" })
        {
            yield return [method, 5];
        }
        for (var width = 0; width <= 8; width++)
        {
            yield return ["UIntBigEndian", width];
            yield return ["UIntLittleEndian", width];
        }
