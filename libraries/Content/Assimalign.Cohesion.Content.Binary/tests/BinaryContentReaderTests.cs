    [Theory(DisplayName = "Cohesion Test [Content.Binary] - Reader: every proper field prefix is transactional truncation")]
    [MemberData(nameof(Fields))]
    public void Read_EveryProperPrefix_ReportsStartWithoutConsuming(string method, int count)
    {
        // Arrange: generated bytes, no container format involved.
        var bytes = PrimitiveBytes.Sequence(count);

        // Act / Assert
        TruncationCorpus.AssertPrefixes(bytes, prefix =>
        {
            var reader = new BinaryContentReader(prefix.Span, baseOffset: 1234);
            try
            {
                ReaderOperations.Read(ref reader, method, count);
                reader.Consumed.ShouldBe(count);
                reader.Position.ShouldBe(1234 + count);
                reader.IsEnd.ShouldBeTrue();
                return true;
            }
            catch (ContentFormatException error)
            {
                reader.Consumed.ShouldBe(0);
                reader.Remaining.ShouldBe(prefix.Length);
                reader.UnreadSpan.SequenceEqual(prefix.Span).ShouldBeTrue();
                error.Position.ShouldBe(1234);
                throw;
            }
        });
    }

    [Theory(DisplayName = "Cohesion Test [Content.Binary] - Reader: Try reads preserve position on every short prefix")]
    [InlineData("Byte", 1)]
    [InlineData("UInt16BigEndian", 2)]
    [InlineData("UInt32BigEndian", 4)]
    [InlineData("UInt64BigEndian", 8)]
    [InlineData("Bytes", 5)]
    public void TryRead_EveryPrefix_ConsumesOnlyCompleteValues(string method, int count)
    {
        // Arrange
        var data = PrimitiveBytes.Sequence(count);

        // Act / Assert
        for (var length = 0; length <= count; length++)
        {
            var reader = new BinaryContentReader(data.AsSpan(0, length), 80);
            ReaderOperations.TryRead(ref reader, method, count).ShouldBe(length == count);
            reader.Consumed.ShouldBe(length == count ? count : 0);
            reader.Position.ShouldBe(length == count ? 80 + count : 80);
        }
    }

    [Fact(DisplayName = "Cohesion Test [Content.Binary] - Reader: insufficient Try values are zero or empty")]
    public void TryRead_EmptyInput_ClearsOutputs()
    {
        // Arrange
        var reader = new BinaryContentReader([]);

        // Act / Assert
        reader.TryReadByte(out var byteValue).ShouldBeFalse();
        byteValue.ShouldBe((byte)0);
        reader.TryReadUInt16BigEndian(out var shortValue).ShouldBeFalse();
        shortValue.ShouldBe((ushort)0);
        reader.TryReadUInt32BigEndian(out var intValue).ShouldBeFalse();
        intValue.ShouldBe(0U);
        reader.TryReadUInt64BigEndian(out var longValue).ShouldBeFalse();
        longValue.ShouldBe(0UL);
        reader.TryReadBytes(1, out var bytes).ShouldBeFalse();
        bytes.IsEmpty.ShouldBeTrue();
        reader.TryReadBytes(0, out bytes).ShouldBeTrue();
    }

    [Fact(DisplayName = "Cohesion Test [Content.Binary] - Reader: failure after progress preserves destination and absolute cursor")]
    public void ReadExactly_AfterProgress_DoesNotChangeDestinationOrCursor()
    {
        // Arrange
        var reader = new BinaryContentReader([1, 2, 3], 900);
        reader.Skip(2);
        byte[] destination = [0xAA, 0xBB];
        ContentFormatException? failure = null;

        // Act
        try
        {
            reader.ReadExactly(destination);
        }
        catch (ContentFormatException error)
        {
            failure = error;
        }

        // Assert
        failure.ShouldNotBeNull();
        failure.ErrorCode.ShouldBe(ContentFormatErrorCode.Truncated);
        failure.Position.ShouldBe(902);
        destination.ShouldBe(new byte[] { 0xAA, 0xBB });
        reader.Consumed.ShouldBe(2);
        reader.ReadByte().ShouldBe((byte)3);
    }

    [Fact(DisplayName = "Cohesion Test [Content.Binary] - Reader: bytes borrow the buffer and zero-length operations are valid")]
    public void ReadBytes_BorrowedData_ExposesOriginalBytes()
    {
        // Arrange
        byte[] data = [1, 2, 3];
        var reader = new BinaryContentReader(data, long.MaxValue - data.Length);

        // Act
        var borrowed = reader.ReadBytes(2);
        data[0] = 9;
        reader.ReadExactly(Span<byte>.Empty);
        reader.Skip(0);

        // Assert
        borrowed[0].ShouldBe((byte)9);
        reader.UnreadSpan[0].ShouldBe((byte)3);
        reader.ReadUtf8String(0).ShouldBe("");
        reader.ReadUIntBigEndian(0).ShouldBe(0UL);
        reader.ReadUIntLittleEndian(0).ShouldBe(0UL);
        reader.Position.ShouldBe(long.MaxValue - 1);
    }

    [Fact(DisplayName = "Cohesion Test [Content.Binary] - Reader: null-terminated UTF-8 consumes NUL or accepts omitted terminators")]
    public void ReadNullTerminatedUtf8String_TerminatedAndOmitted_TracksConsumedBytes()
    {
        // Arrange: UTF-8 produced in code.
        var data = Encoding.UTF8.GetBytes("héllo\0tail");
        var reader = new BinaryContentReader(data, 42);

        // Act / Assert
        reader.ReadNullTerminatedUtf8String().ShouldBe("héllo");
        reader.Consumed.ShouldBe(7);
        reader.ReadNullTerminatedUtf8String().ShouldBe("tail");
        reader.IsEnd.ShouldBeTrue();
        reader.ReadNullTerminatedUtf8String().ShouldBe("");

        var ascii = "payload"u8.ToArray();
        for (var length = 0; length <= ascii.Length; length++)
        {
            var prefix = new BinaryContentReader(ascii.AsSpan(0, length));
            prefix.ReadNullTerminatedUtf8String().ShouldBe(Encoding.UTF8.GetString(ascii.AsSpan(0, length)));
            prefix.Consumed.ShouldBe(length);
        }
        var emptyString = new BinaryContentReader(new byte[] { 0, 65 });
        emptyString.ReadNullTerminatedUtf8String().ShouldBe("");
        emptyString.ReadByte().ShouldBe((byte)65);
    }

    [Fact(DisplayName = "Cohesion Test [Content.Binary] - Reader: numeric and span operations allocate no memory")]
    public void Read_BufferedFields_DoesNotAllocate()
    {
        // Arrange: warm the same operations before measuring.
        byte[] bytes = [0x81, 0x23, 0x45, 0x67, 0x89, 0xAB, 0xCD, 0xEF];
        Span<byte> destination = stackalloc byte[8];
        var checksum = 0UL;
        for (var warmup = 0; warmup < 10; warmup++)
        {
            var reader = new BinaryContentReader(bytes);
            checksum ^= reader.ReadUInt64BigEndian();
        }
        var before = GC.GetAllocatedBytesForCurrentThread();

        // Act
        for (var i = 0; i < 1000; i++)
        {
            var integer = new BinaryContentReader(bytes);
            checksum ^= integer.ReadUInt64LittleEndian();
            var fixedPoint = new BinaryContentReader(bytes);
            checksum ^= (uint)fixedPoint.ReadFixedPoint16x16().RawValue;
            checksum ^= fixedPoint.ReadFourCC().Value;
            var copy = new BinaryContentReader(bytes);
            copy.ReadExactly(destination);
        }
        var allocated = GC.GetAllocatedBytesForCurrentThread() - before;

        // Assert
        allocated.ShouldBe(0);
        checksum.ShouldBe(0UL);
        destination.SequenceEqual(bytes).ShouldBeTrue();
    }

    [Theory(DisplayName = "Cohesion Test [Content.Binary] - Reader: invalid counts are rejected without reading")]
    [InlineData(-1)]
    [InlineData(int.MinValue)]
    public void Read_NegativeCount_ThrowsArgumentError(int count)
    {
        // Arrange / Act / Assert
        foreach (var method in new[] { "Bytes", "Skip", "Utf8String", "UIntBigEndian", "UIntLittleEndian" })
        {
            Should.Throw<ArgumentOutOfRangeException>(() =>
            {
                var reader = new BinaryContentReader(new byte[8]);
                ReaderOperations.Read(ref reader, method, count);
            });
        }
        Should.Throw<ArgumentOutOfRangeException>(() =>
        {
            var reader = new BinaryContentReader([]);
            reader.TryReadBytes(count, out _);
        });
    }

    [Fact(DisplayName = "Cohesion Test [Content.Binary] - Reader: offset and width overflow are argument errors")]
    public void Constructor_ImpossibleOffset_RejectsBeforeReading()
    {
        // Arrange / Act / Assert
        Should.Throw<ArgumentOutOfRangeException>(() => { var reader = new BinaryContentReader([1], -1); });
        Should.Throw<ArgumentOutOfRangeException>(() => { var reader = new BinaryContentReader([1], long.MaxValue); });
        Should.Throw<ArgumentOutOfRangeException>(() => { var reader = new BinaryContentReader([]); reader.ReadUIntBigEndian(9); });
        Should.Throw<ArgumentOutOfRangeException>(() => { var reader = new BinaryContentReader([]); reader.ReadUIntLittleEndian(9); });
    }
}
