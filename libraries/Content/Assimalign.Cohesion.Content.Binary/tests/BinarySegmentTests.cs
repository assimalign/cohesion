using System;
using System.IO;
using System.Threading;
using System.Threading.Tasks;

using Shouldly;
using Xunit;

namespace Assimalign.Cohesion.Content.Binary.Tests;

public class BinarySegmentTests
{
    [Fact(DisplayName = "Cohesion Test [Content.Binary] - Segments: default is empty and materialized")]
    public async Task Default_EmptySegment_SupportsAllReadOperations()
    {
        // Arrange
        BinarySegment segment = default;
        using var destination = new UntouchableStream();

        // Act / Assert
        segment.Length.ShouldBe(0);
        segment.IsEmpty.ShouldBeTrue();
        segment.IsMaterialized.ShouldBeTrue();
        segment.TryGetMemory(out var bytes).ShouldBeTrue();
        bytes.IsEmpty.ShouldBeTrue();
        segment.ToArray(0).ShouldBeEmpty();
        segment.Slice(0, 0).ShouldBe(segment);
        segment.CopyTo(destination);
        await segment.CopyToAsync(destination, CancellationToken.None);
        using var stream = segment.OpenRead();
        stream.ShouldBeOfType<MemoryStream>();
        stream.ReadByte().ShouldBe(-1);
        stream.CanWrite.ShouldBeFalse();
    }

    [Theory(DisplayName = "Cohesion Test [Content.Binary] - Segments: copy-through preserves memory and lazy ranges")]
    [InlineData(false, false)]
    [InlineData(false, true)]
    [InlineData(true, false)]
    [InlineData(true, true)]
    public async Task CopyTo_MemoryAndLazySources_CopiesOnlyRequestedRange(bool lazy, bool asynchronous)
    {
        // Arrange: code-generated bytes with a tail beyond the lazy range.
        var data = PrimitiveBytes.Sequence(32);
        using var memory = new MemoryStream(data);
        using var limit = new ReadLimitStream(memory, 21);
        using var source = new ChunkedReadStream(limit, 2);
        memory.Position = 30;
        var segment = lazy ? BinarySegment.Create(source, 3, 18) : BinarySegment.Create(data.AsMemory(3, 18));
        using var destination = new MemoryStream();

        // Act
        memory.Position.ShouldBe(30);
        source.ReadCalls.ShouldBe(0);
        if (asynchronous)
        {
            await segment.CopyToAsync(destination, CancellationToken.None);
        }
        else
        {
            segment.CopyTo(destination);
        }

        // Assert
        destination.ToArray().ShouldBe(data[3..21]);
        segment.Length.ShouldBe(18);
        segment.IsMaterialized.ShouldBe(!lazy);
        segment.TryGetMemory(out var bytes).ShouldBe(!lazy);
        if (lazy)
        {
            bytes.IsEmpty.ShouldBeTrue();
            memory.Position.ShouldBe(21);
            source.CanRead.ShouldBeTrue();
        }
        else
        {
            bytes.Span.SequenceEqual(data.AsSpan(3, 18)).ShouldBeTrue();
            memory.Position.ShouldBe(30);
        }
    }

    [Fact(DisplayName = "Cohesion Test [Content.Binary] - Segments: lazy subranges borrow the source and remain lazy")]
    public void Slice_LazySegment_OpensBoundedBorrowedStream()
    {
        // Arrange
        var data = PrimitiveBytes.Sequence(20);
        using var source = new TrackingMemoryStream(data);
        var segment = BinarySegment.Create(source, 2, 12);
        var child = segment.Slice(3, 5);

        // Act
        using (var stream = child.OpenRead())
        {
            stream.ShouldBeOfType<ContentSliceStream>();
            stream.Length.ShouldBe(5);
            stream.CanWrite.ShouldBeFalse();
            stream.ReadByte().ShouldBe(5);
        }

        // Assert
        child.IsMaterialized.ShouldBeFalse();
        source.Disposals.ShouldBe(0);
        source.CanRead.ShouldBeTrue();
        child.ToArray(5).ShouldBe(data[5..10]);
        segment.Slice(segment.Length, 0).ShouldBe(default);
    }

    [Fact(DisplayName = "Cohesion Test [Content.Binary] - Segments: memory subranges preserve offset and stay read-only")]
    public void Slice_MemorySegment_OpensReadOnlyMemoryStream()
    {
        // Arrange
        var data = PrimitiveBytes.Sequence(12);
        var segment = BinarySegment.Create(data.AsMemory(2, 8));
        var child = segment.Slice(3, 2);

        // Act
        using var stream = child.OpenRead();
        var buffer = new byte[4];
        var count = stream.Read(buffer);

        // Assert
        stream.ShouldBeOfType<MemoryStream>();
        stream.CanWrite.ShouldBeFalse();
        stream.Length.ShouldBe(2);
        count.ShouldBe(2);
        buffer[..count].ShouldBe(new byte[] { 5, 6 });
        stream.Position.ShouldBe(2);
        child.TryGetMemory(out var memory).ShouldBeTrue();
        memory.Equals(data.AsMemory(5, 2)).ShouldBeTrue();
        child.ToArray(2).ShouldBe(new byte[] { 5, 6 });
    }

    [Fact(DisplayName = "Cohesion Test [Content.Binary] - Segments: non-array memory can open a read-only MemoryStream")]
    public void OpenRead_NonArrayMemory_PreservesPayload()
    {
        // Arrange
        using var memory = new NonArrayMemoryManager(new byte[] { 9, 8, 7 });
        var segment = BinarySegment.Create(memory.Memory);

        // Act
        using var stream = segment.OpenRead();

        // Assert
        stream.ShouldBeOfType<MemoryStream>();
        stream.CanWrite.ShouldBeFalse();
        segment.ToArray(3).ShouldBe(new byte[] { 9, 8, 7 });
        stream.ReadByte().ShouldBe(9);
    }

    [Theory(DisplayName = "Cohesion Test [Content.Binary] - Segments: ToArray enforces the cap before reading")]
    [InlineData(false)]
    [InlineData(true)]
    public void ToArray_AboveCap_ThrowsLimitExceeded(bool lazy)
    {
        // Arrange
        using var source = new ReadLimitStream(new MemoryStream(new byte[16]), 0);
        var segment = lazy ? BinarySegment.Create(source, 3, 8) : BinarySegment.Create(new byte[8]);

        // Act
        var error = Should.Throw<ContentFormatException>(() => segment.ToArray(7));

        // Assert
        error.ErrorCode.ShouldBe(ContentFormatErrorCode.LimitExceeded);
        error.Position.ShouldBe(lazy ? 3L : null);
        source.ReadCalls.ShouldBe(0);
        Should.Throw<ArgumentOutOfRangeException>(() => segment.ToArray(-1));
    }

    [Fact(DisplayName = "Cohesion Test [Content.Binary] - Segments: Int64 payload lengths are refused before materialization")]
    public void ToArray_HugeLazyRange_RejectsWithoutAllocationOrRead()
    {
        // Arrange
        using var source = new LargeLengthStream();
        var segment = BinarySegment.Create(source, 0, long.MaxValue);

        // Act
        var error = Should.Throw<ContentFormatException>(() => segment.ToArray(int.MaxValue));

        // Assert
        error.ErrorCode.ShouldBe(ContentFormatErrorCode.LimitExceeded);
        error.Position.ShouldBe(0);
        segment.Length.ShouldBe(long.MaxValue);
        segment.Slice(long.MaxValue - 1, 1).Length.ShouldBe(1);
        segment.Slice(long.MaxValue, 0).IsEmpty.ShouldBeTrue();
        var arrayLimit = BinarySegment.Create(source, 0, (long)Array.MaxLength + 1);
        Should.Throw<ContentFormatException>(() => arrayLimit.ToArray(int.MaxValue)).ErrorCode.ShouldBe(ContentFormatErrorCode.LimitExceeded);
    }

    [Theory(DisplayName = "Cohesion Test [Content.Binary] - Segments: invalid declared ranges cannot overflow")]
    [InlineData(-1, 0)]
    [InlineData(0, -1)]
    [InlineData(long.MaxValue, 1)]
    [InlineData(1, long.MaxValue)]
    [InlineData(long.MinValue, 1)]
    [InlineData(0, long.MinValue)]
    [InlineData(4, 0)]
    [InlineData(2, 2)]
    public void CreateAndSlice_InvalidRange_ThrowsArgumentError(long offset, long length)
    {
        // Arrange
        using var source = new ReadLimitStream(new MemoryStream(new byte[3]), 0);
        var lazy = BinarySegment.Create(source, 0, 3);
        var memory = BinarySegment.Create(new byte[3]);

        // Act / Assert
        Should.Throw<ArgumentOutOfRangeException>(() => BinarySegment.Create(source, offset, length));
        Should.Throw<ArgumentOutOfRangeException>(() => lazy.Slice(offset, length));
        Should.Throw<ArgumentOutOfRangeException>(() => memory.Slice(offset, length));
        source.ReadCalls.ShouldBe(0);
    }

    [Fact(DisplayName = "Cohesion Test [Content.Binary] - Segments: equality compares backing identity and range")]
    public void Equals_SameAndDifferentBacking_UsesIdentityAndRange()
    {
        // Arrange
        byte[] bytes = [1, 2, 3];
        var memory = BinarySegment.Create(bytes);
        using var source = new MemoryStream(bytes);
        var lazy = BinarySegment.Create(source, 0, 3);

        // Act / Assert
        memory.Equals(BinarySegment.Create(bytes)).ShouldBeTrue();
        memory.Equals(BinarySegment.Create(new byte[] { 1, 2, 3 })).ShouldBeFalse();
        lazy.Equals(BinarySegment.Create(source, 0, 3)).ShouldBeTrue();
        lazy.Equals(BinarySegment.Create(source, 1, 2)).ShouldBeFalse();
        lazy.Equals(memory).ShouldBeFalse();
        lazy.Equals((object)BinarySegment.Create(source, 0, 3)).ShouldBeTrue();
        lazy.GetHashCode().ShouldBe(BinarySegment.Create(source, 0, 3).GetHashCode());
        lazy.Equals((object)source).ShouldBeFalse();
        BinarySegment.Create(ReadOnlyMemory<byte>.Empty).ShouldBe(default);
        BinarySegment.Create(source, 0, 0).ShouldBe(default);
    }

    [Fact(DisplayName = "Cohesion Test [Content.Binary] - Segments: invalid sources and canceled copies are rejected")]
    public async Task CopyToAsync_InvalidSourceOrCanceledToken_PreservesDestination()
    {
        // Arrange
        using var source = new NonSeekableStream(new MemoryStream(new byte[3]));
        using var destination = new MemoryStream();
        using var cancellation = new CancellationTokenSource();
        cancellation.Cancel();
        var segment = BinarySegment.Create(new byte[] { 1, 2, 3 });

        // Act / Assert
        Should.Throw<ArgumentException>(() => BinarySegment.Create(source, 0, 1));
        Should.Throw<ArgumentNullException>(() => BinarySegment.Create(null!, 0, 1));
        Should.Throw<ArgumentNullException>(() => segment.CopyTo(null!));
        await Should.ThrowAsync<ArgumentNullException>(() => segment.CopyToAsync(null!, CancellationToken.None).AsTask());
        await Should.ThrowAsync<OperationCanceledException>(() => segment.CopyToAsync(destination, cancellation.Token).AsTask());
        destination.Length.ShouldBe(0);
    }
}
