    }
    [Fact(DisplayName = "Cohesion Test [Content.Pdf] - ISO 32000-2 §7.5.2 and §7.5.4: Header and classic xref records use exact encodings")]
    public void Write_ClassicTable_UsesBinaryMarkerAndTwentyByteRows()
    {
        // Arrange
        using var source = new MemoryStream(PdfFixtureBuilder.Classic()); using var document = new PdfReader().Read(source);
        using var output = new MemoryStream();
        // Act
        new PdfWriter().Write(output, document); var bytes = output.ToArray();
        // Assert
        bytes.AsSpan(0, 9).ToArray().ShouldBe("%PDF-1.7\n"u8.ToArray());
        bytes.AsSpan(9, 6).ToArray().ShouldBe(new byte[] { 37, 226, 227, 207, 211, 10 });
        var xref = (int)PdfFixtureBuilder.StartXref(bytes);
        Encoding.ASCII.GetString(bytes, xref, 9).ShouldBe("xref\n0 4\n");
        for (var i = 0; i < 4; i++)
        {
            var row = bytes.AsSpan(xref + 9 + i * 20, 20);
            row[10].ShouldBe((byte)' '); row[16].ShouldBe((byte)' '); row[18].ShouldBe((byte)' '); row[19].ShouldBe((byte)'\n');
        }
    }
    [Fact(DisplayName = "Cohesion Test [Content.Pdf] - ISO 32000-2 §7.4.4.4 and §7.5.8: Xref stream uses Flate PNG Up and indexes itself")]
    public void Write_CrossReferenceStream_UsesPredictorAndSelfEntry()
    {
        // Arrange
        using var source = new MemoryStream(PdfFixtureBuilder.Classic()); using var document = new PdfReader().Read(source);
        using var output = new MemoryStream();
        // Act
        PdfWriter.Create(new() { UseCrossReferenceStream = true }).Write(output, document); output.Position = 0;
        using var saved = new PdfReader().Read(output);
        // Assert
        var xrefId = PdfObjectIdentifier.Create(4);
        var stream = saved.Resolve(xrefId).ShouldBeOfType<PdfStream>();
        stream.Dictionary.Get("Filter").ShouldBeOfType<PdfName>().ToString().ShouldBe("/FlateDecode");
        var parameters = stream.Dictionary.Get("DecodeParms").ShouldBeOfType<PdfDictionary>();
        parameters.Get("Predictor").ShouldBeOfType<PdfInteger>().Value.ShouldBe(12);
        parameters.Get("Columns").ShouldBeOfType<PdfInteger>().Value.ShouldBe(13);
        var bytes = stream.Decode(); bytes.Length.ShouldBe(5 * 13);
        var reader = new BinaryContentReader(bytes.Span.Slice(4 * 13, 13));
        reader.ReadByte().ShouldBe((byte)1); reader.ReadUInt64BigEndian().ShouldBe((ulong)saved.StartXref);
    }
    [Theory(DisplayName = "Cohesion Test [Content.Pdf] - ISO 32000-2 §7.5.4 and §7.5.7: Nonzero generations stay unpacked and freeing saturates")]
    [InlineData(7)]
    [InlineData(65535)]
    public void Write_NonzeroGeneration_PreservesIdentityAndFreeGeneration(int generation)
    {
        // Arrange
        using var source = new MemoryStream(PdfFixtureBuilder.Generation(generation)); using var document = new PdfReader().Read(source);
        using var packed = new MemoryStream();
        // Act
        PdfWriter.Create(new() { UseCrossReferenceStream = true, PackObjects = true }).Write(packed, document); packed.Position = 0;
        using var saved = new PdfReader().Read(packed);
        // Assert
        saved.CrossReferences[4].Kind.ShouldBe(PdfCrossReferenceKind.Uncompressed);
        var id = PdfObjectIdentifier.Create(4, generation); saved.Resolve(id).ShouldBeOfType<PdfString>();
        saved.Free(id); using var update = new MemoryStream(); PdfWriter.Create(new() { Incremental = true }).Write(update, saved); update.Position = 0;
        using var deleted = new PdfReader().Read(update);
        deleted.CrossReferences[4].Identifier.Generation.ShouldBe(Math.Min(65535, generation + 1));
        deleted.Resolve(id).ShouldBeOfType<PdfNull>();
    }
    [Fact(DisplayName = "Cohesion Test [Content.Pdf] - ISO 32000-2 §7.5.7: Object stream batches are bounded and retain member order")]
    public void Write_ManyObjects_UsesMultipleBoundedObjectStreams()
    {
        // Arrange
        using var source = new MemoryStream(PdfFixtureBuilder.Classic()); using var document = new PdfReader().Read(source);
        for (var i = 0; i < 205; i++) { document.Add(PdfInteger.Create(i)); }
        using var output = new MemoryStream();
        // Act
        PdfWriter.Create(new() { UseCrossReferenceStream = true, PackObjects = true }).Write(output, document); output.Position = 0;
        using var saved = new PdfReader().Read(output);
        // Assert
        var streams = 0;
        foreach (var entry in saved.CrossReferences.Values)
        {
            if (entry.Kind != PdfCrossReferenceKind.Uncompressed) { continue; }
            if (saved.Resolve(entry.Identifier) is PdfStream stream && PdfFileLoader.IsName(stream.Dictionary.Get("Type"), "ObjStm"))
            {
                streams++; stream.Dictionary.Get("N").ShouldBeOfType<PdfInteger>().Value.ShouldBeLessThanOrEqualTo(100);
            }
        }
        streams.ShouldBe(3); PdfWriterAssertions.Graphs(document, saved);
    }
    [Theory(DisplayName = "Cohesion Test [Content.Pdf] - ISO 32000-2 §7.5.6: Output failure and cancellation leave source bytes unchanged")]
    [InlineData(false)]
    [InlineData(true)]
    public async Task WriteAsync_FailedDestination_LeavesOriginalUntouched(bool incremental)
    {
        // Arrange
        var bytes = PdfFixtureBuilder.Classic(); using var source = new MemoryStream(bytes.AsSpan().ToArray());
        using var document = new PdfReader().Read(source); var writer = PdfWriter.Create(new() { Incremental = incremental });
        using var failure = new PdfFailingWriteStream();
        using var cancellation = new CancellationTokenSource(); using var canceled = new PdfFailingWriteStream(cancellation);
        // Act / Assert
        Should.Throw<IOException>(() => writer.Write(failure, document));
        await Should.ThrowAsync<OperationCanceledException>(async () => await writer.WriteAsync(canceled, document, cancellation.Token));
        source.ToArray().ShouldBe(bytes); source.CanRead.ShouldBeTrue();
        using var retry = new MemoryStream(); writer.Write(retry, document); retry.Position = 0;
        using var saved = new PdfReader().Read(retry); saved.PageCount.ShouldBe(1);
    }
    [Fact(DisplayName = "Cohesion Test [Content.Pdf] - ISO 32000-2 §7.5: Writer arguments and allocation limits fail explicitly")]
    public void Write_InvalidOptionsAndModel_RejectsBeforeUnboundedAllocation()
    {
        // Arrange
        using var source = new MemoryStream(PdfFixtureBuilder.Classic()); using var document = new PdfReader().Read(source);
        using var output = new MemoryStream();
        // Act / Assert
        Should.Throw<ArgumentNullException>(() => PdfWriter.Create(null!));
        Should.Throw<ArgumentOutOfRangeException>(() => PdfWriter.Create(new() { MaxBufferedBytes = 0 }));
        Should.Throw<ArgumentOutOfRangeException>(() => PdfWriter.Create(new() { MaxDepth = 513 }));
        Should.Throw<ArgumentOutOfRangeException>(() => PdfWriter.Create(new() { MaxObjects = 0 }));
        Should.Throw<ArgumentException>(() => PdfWriter.Create(new() { PackObjects = true }));
        Should.Throw<ArgumentNullException>(() => new PdfWriter().Write(null!, document));
        Should.Throw<ArgumentNullException>(() => new PdfWriter().Write(output, null!));
        Should.Throw<ArgumentException>(() => new PdfWriter().Write(source, document));
        document.Trailer[PdfName.Create("Size"u8)] = PdfInteger.Create(long.MaxValue);
        Should.Throw<ContentFormatException>(() => new PdfWriter().Write(output, document)).ErrorCode.ShouldBe(ContentFormatErrorCode.LimitExceeded);
        Should.Throw<ContentFormatException>(() => document.Add(new PdfNull())).ErrorCode.ShouldBe(ContentFormatErrorCode.LimitExceeded);
        output.Length.ShouldBe(0);
        document.Dispose(); Should.Throw<ObjectDisposedException>(() => new PdfWriter().Write(output, document));
    }
