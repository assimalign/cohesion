    [Theory(DisplayName = "Cohesion Test [Content.Pdf] - ISO 32000-2 §7.5.4–§7.5.8: Writer goldens reload and round-trip in both save modes")]
    [InlineData("WRITER_TABLE")]
    [InlineData("WRITER_XREF")]
    [InlineData("WRITER_OBJECTS")]
    [InlineData("WRITER_INCREMENTAL_TABLE")]
    [InlineData("WRITER_INCREMENTAL_STREAM")]
    [InlineData("WRITER_INCREMENTAL_HYBRID")]
    public void Read_WriterGolden_PreservesGraphsAcrossSaves(string name)
    {
        // Arrange: generated with PdfWriterGoldenBuilder.Build(name), never generated by this test.
        var bytes = File.ReadAllBytes(Path.Combine(AppContext.BaseDirectory, "TestObjects", "Golden", name + ".pdf"));
        using var source = new MemoryStream(bytes); using var document = new PdfReader().Read(source);
        // Act / Assert
        Encoding.Latin1.GetString(bytes).ShouldContain("% Generated by Assimalign.Cohesion.Content.Pdf.PdfWriter:", Case.Sensitive);
        document.PageCount.ShouldBe(name == "WRITER_INCREMENTAL_HYBRID" ? 1 : 2);
        foreach (var incremental in new[] { false, true })
        {
            using var output = new MemoryStream(); PdfWriter.Create(new() { Incremental = incremental }).Write(output, document);
            output.Position = 0; using var saved = new PdfReader().Read(output);
            PdfWriterAssertions.Graphs(document, saved);
            if (incremental) { output.ToArray().AsSpan(0, bytes.Length).ToArray().ShouldBe(bytes); }
        }
    }
