    [Theory(DisplayName = "Cohesion Test [Content.Pdf] - ISO 32000-2 §7.5: Identical model and options produce identical bytes")]
    [InlineData(0)]
    [InlineData(1)]
    [InlineData(2)]
    [InlineData(3)]
    [InlineData(4)]
    [InlineData(5)]
    public void Write_RepeatedSaves_AreByteIdentical(int mode)
    {
        // Arrange
        var bytes = mode == 4 ? PdfFixtureBuilder.XrefStream() : mode == 5 ? PdfFixtureBuilder.XrefStream(objectStream: true, hybrid: true) : PdfFixtureBuilder.InheritedPages();
        using var source = new MemoryStream(bytes); using var document = new PdfReader().Read(source);
        document.Pages[0].Dictionary[PdfName.Create("Rotate"u8)] = PdfInteger.Create(270);
        document.Add(PdfString.Create("same"u8));
        var writer = PdfWriter.Create(new() { Incremental = mode >= 3, UseCrossReferenceStream = mode is 1 or 2, PackObjects = mode == 2 });
        using var first = new MemoryStream(); using var second = new MemoryStream();
