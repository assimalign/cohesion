    [Fact(DisplayName = "Cohesion Test [Content.Pdf] - ISO 32000-2 §7.5.8.4: Inherited hybrid trailer metadata does not change the last table style")]
    public void Write_TableAfterHybrid_UsesLastSectionInsteadOfMergedTrailer()
    {
        // Arrange: a table-only update follows a hybrid revision and inherits its old XRefStm key.
        var bytes = PdfFixtureBuilder.XrefStream(objectStream: true, hybrid: true);
        using var source = new MemoryStream(); source.Write(bytes);
        var table = source.Position;
        PdfFixtureBuilder.Write(source, $"xref\n0 1\n0000000000 65535 f \ntrailer\n<< /Size 7 /Root 1 0 R /Prev {PdfFixtureBuilder.StartXref(bytes)} >>\nstartxref\n{table}\n%%EOF\n");
        source.Position = 0; using var document = new PdfReader().Read(source);
        document.LastCrossReferenceStyle.ShouldBe(PdfCrossReferenceStyle.Table);
        document.Trailer.Get("XRefStm").ShouldBeOfType<PdfInteger>();
        using var output = new MemoryStream();
        // Act
        PdfWriter.Create(new() { Incremental = true }).Write(output, document); output.Position = 0;
        using var saved = new PdfReader().Read(output);
        // Assert
        saved.LastCrossReferenceStyle.ShouldBe(PdfCrossReferenceStyle.Table);
        var appended = Encoding.Latin1.GetString(output.ToArray().AsSpan((int)source.Length));
        appended.ShouldNotContain("/XRefStm", Case.Sensitive); PdfWriterAssertions.Graphs(document, saved);
    }
