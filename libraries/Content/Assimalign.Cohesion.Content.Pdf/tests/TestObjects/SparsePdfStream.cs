using System;
using System.Globalization;
using System.IO;
using System.Text;

namespace Assimalign.Cohesion.Content.Pdf.Tests;

// A 40 GiB PDF backed by two small segments; unread payload bytes are implicit zeros.
internal sealed class SparsePdfStream : Stream
{
    private readonly byte[] _prefix;
    private readonly byte[] _suffix;
    private readonly long _suffixOffset;
    internal const long PayloadLength = 40L * 1024 * 1024 * 1024;
    internal long BytesRead { get; private set; }
    internal SparsePdfStream()
    {
        using var prefix = new MemoryStream();
        PdfFixtureBuilder.Write(prefix, "%PDF-1.7\n% Generated by SparsePdfStream\n");
        var offsets = new long[4];
        for (var i = 0; i < 3; i++)
        {
            offsets[i] = prefix.Position;
            PdfFixtureBuilder.Write(prefix, $"{i + 1} 0 obj\n{PdfFixtureBuilder.BasicObjects[i]}\nendobj\n");
        }
        offsets[3] = prefix.Position;
        PdfFixtureBuilder.Write(prefix, $"4 0 obj\n<< /Length {PayloadLength} >>\nstream\n");
        _prefix = prefix.ToArray(); _suffixOffset = _prefix.Length + PayloadLength;
        var suffix = new StringBuilder("\nendstream\nendobj\n");
        var xref = _suffixOffset + suffix.Length;
        suffix.Append("xref\n0 5\n0000000000 65535 f \n");
        foreach (var offset in offsets) { suffix.Append(offset.ToString("D10", CultureInfo.InvariantCulture)).Append(" 00000 n \n"); }
        suffix.Append($"trailer\n<< /Size 5 /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n");
        _suffix = Encoding.ASCII.GetBytes(suffix.ToString());
    }
    public override bool CanRead => true;
    public override bool CanSeek => true;
    public override bool CanWrite => false;
    public override long Length => _suffixOffset + _suffix.Length;
    public override long Position { get; set; }
    public override int Read(byte[] buffer, int offset, int count) => Read(buffer.AsSpan(offset, count));
    public override int Read(Span<byte> buffer)
    {
        var count = (int)Math.Min(buffer.Length, Math.Max(0, Length - Position));
        var target = buffer[..count]; target.Clear();
        if (Position < _prefix.Length) { _prefix.AsSpan((int)Position, (int)Math.Min(count, _prefix.Length - Position)).CopyTo(target); }
        var overlap = Math.Max(Position, _suffixOffset);
        if (overlap < Position + count)
        {
            _suffix.AsSpan((int)(overlap - _suffixOffset), (int)(Position + count - overlap)).CopyTo(target[(int)(overlap - Position)..]);
        }
        Position += count; BytesRead += count; return count;
    }
    public override long Seek(long offset, SeekOrigin origin) => Position = origin switch { SeekOrigin.Begin => offset, SeekOrigin.Current => Position + offset, _ => Length + offset };
    public override void Flush() { }
    public override void SetLength(long value) => throw new NotSupportedException();
    public override void Write(byte[] buffer, int offset, int count) => throw new NotSupportedException();
}
