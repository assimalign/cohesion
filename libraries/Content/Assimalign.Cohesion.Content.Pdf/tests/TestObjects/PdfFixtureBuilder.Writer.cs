using System.Globalization;
using System.IO;

namespace Assimalign.Cohesion.Content.Pdf.Tests;

internal static partial class PdfFixtureBuilder
{
    internal static byte[] Generation(int generation)
    {
        using var output = new MemoryStream();
        Write(output, "%PDF-1.7\n% Generated by PdfFixtureBuilder.Generation\n");
        var offsets = new long[4];
        for (var i = 0; i < 4; i++)
        {
            offsets[i] = output.Position;
            Write(output, $"{i + 1} {(i == 3 ? generation : 0)} obj\n{(i == 3 ? "(generation)" : BasicObjects[i])}\nendobj\n");
        }
        var xref = output.Position;
        Write(output, "xref\n0 5\n0000000000 65535 f \n");
        for (var i = 0; i < 4; i++)
        {
            Write(output, offsets[i].ToString("D10", CultureInfo.InvariantCulture) + " " + (i == 3 ? generation : 0).ToString("D5", CultureInfo.InvariantCulture) + " n \n");
        }
        Write(output, $"trailer\n<< /Size 5 /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n");
        return output.ToArray();
    }
}
