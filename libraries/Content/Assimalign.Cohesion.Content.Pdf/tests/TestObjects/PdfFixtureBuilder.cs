using System;
using System.Globalization;
using System.IO;
using System.IO.Compression;
using System.Text;

namespace Assimalign.Cohesion.Content.Pdf.Tests;

// All fixtures are locally generated, license-clean bytes. No external PDF corpus is used.
internal static partial class PdfFixtureBuilder
{
    internal static readonly string[] BasicObjects =
    {
        "<< /Type /Catalog /Pages 2 0 R >>",
        "<< /Type /Pages /Kids [3 0 R] /Count 1 /MediaBox [0 0 612 792] /Resources <<>> >>",
        "<< /Type /Page /Parent 2 0 R >>"
    };
    internal static byte[] Classic(string[]? objects = null, string trailer = "", string prefix = "")
    {
        objects ??= BasicObjects;
        using var output = new MemoryStream();
        Write(output, prefix + "%PDF-1.7\n% Generated by PdfFixtureBuilder.Classic\n");
        var offsets = new long[objects.Length];
        for (var i = 0; i < objects.Length; i++)
        {
            offsets[i] = output.Position;
            Write(output, $"{i + 1} 0 obj\n{objects[i]}\nendobj\n");
        }
        var xref = output.Position;
        Write(output, $"xref\n0 {objects.Length + 1}\n0000000000 65535 f \n");
        foreach (var offset in offsets) { Write(output, offset.ToString("D10", CultureInfo.InvariantCulture) + " 00000 n \n"); }
        Write(output, $"trailer\n<< /Size {objects.Length + 1} /Root 1 0 R {trailer} >>\nstartxref\n{xref}\n%%EOF\n");
        return output.ToArray();
    }
    internal static byte[] Compress(ReadOnlySpan<byte> bytes)
    {
        using var output = new MemoryStream();
        using (var compressor = new ZLibStream(output, CompressionLevel.SmallestSize, true)) { compressor.Write(bytes); }
        return output.ToArray();
    }
    internal static void Write(Stream output, string text) => output.Write(Encoding.Latin1.GetBytes(text));
    internal static byte[] Replace(byte[] bytes, string oldValue, string newValue) => Encoding.Latin1.GetBytes(Encoding.Latin1.GetString(bytes).Replace(oldValue, newValue, StringComparison.Ordinal));
    internal static long StartXref(byte[] bytes)
    {
        var text = Encoding.Latin1.GetString(bytes);
        var start = text.LastIndexOf("startxref\n", StringComparison.Ordinal) + 10;
        return long.Parse(text.AsSpan(start, text.IndexOf('\n', start) - start), CultureInfo.InvariantCulture);
    }
}
