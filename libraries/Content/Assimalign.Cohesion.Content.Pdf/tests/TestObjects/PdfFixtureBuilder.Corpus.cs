    internal static byte[] XrefStream(bool objectStream = false, bool hybrid = false, bool predictor = true, string extra = "", Action<byte[]>? mutateRows = null, string? objectStreamHeader = null, int objectStreamCount = 2)
    {
        using var output = new MemoryStream();
        Write(output, "%PDF-2.0\n% Generated by PdfFixtureBuilder.XrefStream\n");
        var offsets = new long[7];
        void Object(int number, string body)
        {
            offsets[number] = output.Position;
            Write(output, $"{number} 0 obj\n{body}\nendobj\n");
        }
        Object(1, BasicObjects[0]); Object(2, BasicObjects[1]);
        if (!objectStream) { Object(3, BasicObjects[2]); Object(6, "<< /Example 42 >>"); }
        if (objectStream)
        {
            var firstBody = BasicObjects[2];
            var header = objectStreamHeader ?? $"3 0 6 {Encoding.Latin1.GetByteCount(firstBody) + 1} ";
            var content = Compress(Encoding.Latin1.GetBytes(header + firstBody + "\n<< /Example 42 >>"));
            Object(4, $"<< /Type /ObjStm /N {objectStreamCount} /First {header.Length} /Length {content.Length} /Filter /FlateDecode >>\nstream\n{Encoding.Latin1.GetString(content)}\nendstream");
        }
        else { Object(4, "<< /Unused true >>"); }
        offsets[5] = output.Position;
        var rows = new byte[7 * 7];
        for (var number = 0; number < 7; number++)
        {
            var row = rows.AsSpan(number * 7, 7);
            row[0] = number == 0 ? (byte)0 : objectStream && number is 3 or 6 ? (byte)2 : (byte)1;
            BinaryPrimitives.WriteUInt32BigEndian(row[1..], row[0] == 2 ? 4U : (uint)offsets[number]);
            BinaryPrimitives.WriteUInt16BigEndian(row[5..], number == 0 ? (ushort)65535 : number == 6 && objectStream ? (ushort)1 : (ushort)0);
        }
        mutateRows?.Invoke(rows);
        var encoded = Compress(predictor ? PngUp(rows, 7) : rows);
        Object(5, $"<< /Type /XRef /Size 7 /Root 1 0 R /W [1 4 2] /Index [0 7] /Length {encoded.Length} /Filter /FlateDecode {(predictor ? "/DecodeParms << /Predictor 12 /Columns 7 >>" : "")} {extra} >>\nstream\n{Encoding.Latin1.GetString(encoded)}\nendstream");
        var startXref = offsets[5];
        if (hybrid)
        {
            startXref = output.Position;
            Write(output, "xref\n0 7\n0000000000 65535 f \n");
            for (var number = 1; number < 7; number++)
            {
                // Deliberately conflicting table records demonstrate supplement precedence.
                if (objectStream && number is 3 or 6) { Write(output, "0000000000 00000 f \n"); }
                else { Write(output, (number == 1 ? offsets[2] : offsets[number]).ToString("D10", CultureInfo.InvariantCulture) + " 00000 n \n"); }
            }
            Write(output, $"trailer\n<< /Size 7 /Root 1 0 R /XRefStm {offsets[5]} >>\n");
        }
        Write(output, $"startxref\n{startXref}\n%%EOF\n");
        return output.ToArray();
    }
    internal static byte[] PngUp(byte[] rows, int columns)
    {
        var encoded = new byte[rows.Length + rows.Length / columns];
        for (var row = 0; row < rows.Length / columns; row++)
        {
            var offset = row * (columns + 1); encoded[offset] = 2;
            for (var column = 0; column < columns; column++)
            {
                encoded[offset + 1 + column] = (byte)(rows[row * columns + column] - (row == 0 ? 0 : rows[(row - 1) * columns + column]));
            }
        }
        return encoded;
    }
    internal static byte[] Incremental(bool stream = false)
    {
        var initial = Classic(new[] { BasicObjects[0], BasicObjects[1], BasicObjects[2], "(retired)" });
        using var output = new MemoryStream(); output.Write(initial);
        Write(output, "% Generated by PdfFixtureBuilder.Incremental\n");
        var page = output.Position;
        Write(output, "3 0 obj\n<< /Type /Page /Parent 2 0 R /Rotate 90 >>\nendobj\n");
        var added = output.Position;
        Write(output, "5 0 obj\n(new revision)\nendobj\n");
        var xref = output.Position;
        if (stream)
        {
            var rows = new byte[4 * 7];
            for (var i = 0; i < 4; i++)
            {
                var row = rows.AsSpan(i * 7, 7); row[0] = i == 1 ? (byte)0 : (byte)1;
                BinaryPrimitives.WriteUInt32BigEndian(row[1..], (uint)(i == 0 ? page : i == 2 ? added : i == 3 ? xref : 0));
                BinaryPrimitives.WriteUInt16BigEndian(row[5..], i == 1 ? (ushort)1 : (ushort)0);
            }
            Write(output, $"7 0 obj\n<< /Type /XRef /Size 8 /Root 1 0 R /Prev {StartXref(initial)} /Index [3 3 7 1] /W [1 4 2] /Length {rows.Length} >>\nstream\n");
            output.Write(rows); Write(output, "\nendstream\nendobj\n");
        }
        else
        {
            Write(output, $"xref\n3 3\n{page.ToString("D10", CultureInfo.InvariantCulture)} 00000 n \n0000000000 00001 f \n{added.ToString("D10", CultureInfo.InvariantCulture)} 00000 n \ntrailer\n<< /Size 6 /Root 1 0 R /Prev {StartXref(initial)} >>\n");
        }
        Write(output, $"startxref\n{xref}\n%%EOF\n");
        return output.ToArray();
    }
