            builder.AppendLine(
                $"            new({Quote(endpoint.Name)}, {Quote(endpoint.Scheme)}, {endpoint.ContainerPort.ToString(CultureInfo.InvariantCulture)}, {devPort}),");
        }
        builder.AppendLine("        },");
        builder.AppendLine("        new ResourceSettingDefault[]");
        builder.AppendLine("        {");
        foreach (ResourceSettingModel setting in settings)
        {
            builder.AppendLine($"            new({Quote(setting.Key)}, {QuoteNullable(setting.Default)}),");
