        builder.AppendLine("            Settings = settings;");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        internal global::System.Collections.Generic.IReadOnlyList<ResourceEndpointDefault> Endpoints { get; }");
        builder.AppendLine();
