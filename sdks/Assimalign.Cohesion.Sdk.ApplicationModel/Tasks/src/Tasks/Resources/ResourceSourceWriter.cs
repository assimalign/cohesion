    public static void WriteResource(string path, string rootNamespace, ResourceManifestModel manifest)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(path))!);

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine($"namespace {rootNamespace};");
        builder.AppendLine();
        builder.AppendLine("/// <summary>Provides strongly typed access to this Cohesion resource's runtime inputs.</summary>");
        builder.AppendLine("public static partial class Resource");
        builder.AppendLine("{");
        builder.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        builder.AppendLine("    internal static void RegisterEndpointCertificates()");
        builder.AppendLine("    {");
        builder.AppendLine("        global::Assimalign.Cohesion.Hosting.Resources.ResourceRuntime.RegisterEndpointCertificates(typeof(Resource).Assembly,");
        builder.AppendLine("            new global::System.Collections.Generic.Dictionary<string, string>(global::System.StringComparer.OrdinalIgnoreCase)");
        builder.AppendLine("            {");
        foreach (ResourceEndpointModel endpoint in manifest.Endpoints.Where(endpoint => !string.IsNullOrEmpty(endpoint.Certificate)))
        {
            builder.AppendLine($"                [{Quote(endpoint.Name)}] = {Quote(endpoint.Certificate ?? string.Empty)},");
        }
        builder.AppendLine("            });");
        builder.AppendLine("    }");
        builder.AppendLine("    /// <summary>Gets the resource name.</summary>");
        builder.AppendLine($"    public const string Name = {Quote(manifest.Name)};");
        builder.AppendLine();
        builder.AppendLine("    /// <summary>Gets the containing application name.</summary>");
        builder.AppendLine($"    public const string Application = {Quote(manifest.Application)};");
        builder.AppendLine();
        builder.AppendLine("    /// <summary>Gets the resource kind.</summary>");
        builder.AppendLine($"    public const string Kind = {Quote(manifest.Kind)};");
        builder.AppendLine();
        WriteManifestDefaults(builder, manifest.Endpoints, manifest.Settings);
        WriteSettingValueType(builder);
        if (manifest.References.Count > 0)
        {
            WriteReferenceEndpointType(builder);
        }
        WriteEndpoints(builder, manifest.Endpoints);
        WriteMounts(builder, manifest.Mounts);
        WriteSettings(builder, manifest.Settings);
        WriteReferences(builder, manifest.References);
        builder.AppendLine("}");
        builder.AppendLine();
        builder.AppendLine("/// <summary>Provides a compiler-rooted assembly anchor for generated gateway bindings.</summary>");
        builder.Append("public static class ").AppendLine(EntryAnchorType(manifest.Artifact.Assembly));
        builder.AppendLine("{");
        builder.AppendLine("}");

        ResourceFileWriter.WriteIfChanged(
            path,
            new UTF8Encoding(encoderShouldEmitUTF8Identifier: false).GetBytes(builder.ToString()));
    }

    public static void WriteControlPlane(
        string path,
        string rootNamespace,
        string controlPlaneType,
        ResourceManifestModel manifest)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(path))!);

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");

        if (string.IsNullOrWhiteSpace(controlPlaneType))
        {
            ResourceFileWriter.WriteIfChanged(
                path,
                new UTF8Encoding(encoderShouldEmitUTF8Identifier: false).GetBytes(builder.ToString()));
            return;
        }

        builder.AppendLine();
        builder.AppendLine($"namespace {rootNamespace};");
        builder.AppendLine();
        builder.AppendLine("internal static class __CohesionResourceControlPlaneRegistration");
        builder.AppendLine("{");
        builder.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        builder.AppendLine("    internal static void Register()");
        builder.AppendLine("    {");
        builder.AppendLine("        global::Assimalign.Cohesion.Hosting.Resources.ResourceRuntime.RegisterEntry(typeof(Resource).Assembly);");
        builder.AppendLine("        global::Assimalign.Cohesion.Hosting.Resources.ResourceRuntime.RegisterControlPlane(");
        builder.AppendLine("            typeof(Resource).Assembly,");
        builder.AppendLine("            static () => CreateControlPlane(),");
        builder.AppendLine($"            {manifest.Lifecycle.StopGraceSeconds.ToString(CultureInfo.InvariantCulture)});");
        builder.AppendLine("    }");
        builder.AppendLine();
        builder.AppendLine("    private static global::Assimalign.Cohesion.Hosting.Resources.IResourceControlPlane CreateControlPlane()");
        builder.AppendLine("    {");
        builder.AppendLine($"        global::Assimalign.Cohesion.Hosting.Resources.IResourceControlPlane controlPlane = global::{controlPlaneType}.Create();");
        builder.AppendLine("        global::Assimalign.Cohesion.Hosting.Resources.ResourceContext context = global::Assimalign.Cohesion.Hosting.Resources.ResourceRuntime.Current;");
        for (int index = 0; index < manifest.Endpoints.Count; index++)
        {
            ResourceEndpointModel endpoint = manifest.Endpoints[index];
            string devPort = endpoint.DevPort is int port
                ? port.ToString(CultureInfo.InvariantCulture)
                : "null";
            builder.AppendLine(
                $"        if (context.TryGetEndpoint({Quote(endpoint.Name)}, {Quote(endpoint.Scheme)}, {devPort}, out global::System.Uri? endpoint{index.ToString(CultureInfo.InvariantCulture)}))");
            builder.AppendLine("        {");
            builder.AppendLine(
                $"            controlPlane.ObserveEndpoint({Quote(endpoint.Name)}, endpoint{index.ToString(CultureInfo.InvariantCulture)});");
            builder.AppendLine("        }");
        }
        builder.AppendLine();
        builder.AppendLine("        return controlPlane;");
        builder.AppendLine("    }");
        builder.AppendLine("}");

        ResourceFileWriter.WriteIfChanged(
            path,
            new UTF8Encoding(encoderShouldEmitUTF8Identifier: false).GetBytes(builder.ToString()));
    }

    public static string Identifier(string value) => CohesionIdentifier.ToPascalCase(value);

    private static string EntryAnchorType(string assemblyName) =>
        "CohesionResourceEntry" + Convert.ToHexString(Encoding.UTF8.GetBytes(assemblyName));

