    private static string SettingType(string value)
    {
        return value.ToLowerInvariant() switch
        {
            "string" => "string",
            "int" or "int32" => "int",
            "bool" or "boolean" => "bool",
            "timespan" or "system.timespan" => "global::System.TimeSpan",
            "uri" or "system.uri" => "global::System.Uri",
            _ when value.StartsWith("global::", StringComparison.Ordinal) => value.Replace('+', '.'),
            _ when value.Contains('.', StringComparison.Ordinal) || value.Contains('+', StringComparison.Ordinal) =>
                $"global::{value.Replace('+', '.')}",
            _ => value
        };
    }

    private static string SettingParser(string type)
    {
        return type switch
        {
            "string" => "static value => value",
            "int" => "static value => int.Parse(value, global::System.Globalization.NumberStyles.Integer, global::System.Globalization.CultureInfo.InvariantCulture)",
            "bool" => "static value => bool.Parse(value)",
            "global::System.TimeSpan" => "static value => global::System.TimeSpan.Parse(value, global::System.Globalization.CultureInfo.InvariantCulture)",
            "global::System.Uri" => "static value => new global::System.Uri(value, global::System.UriKind.Absolute)",
            _ => $"static value => SettingValue<{type}>.ParseEnum<{type}>(value)"
        };
    }

    private static string QuoteNullable(string? value)
    {
        return value is null ? "null" : Quote(value);
    }

    private static string Quote(string value)
    {
        var builder = new StringBuilder(value.Length + 2);
        builder.Append('"');
        foreach (char character in value)
        {
            switch (character)
            {
                case '\\':
                    builder.Append("\\\\");
                    break;
                case '"':
                    builder.Append("\\\"");
                    break;
                case '\r':
                    builder.Append("\\r");
                    break;
                case '\n':
                    builder.Append("\\n");
                    break;
                case '\t':
                    builder.Append("\\t");
                    break;
                case '\u0085':
                    builder.Append("\\u0085");
                    break;
                case '\u2028':
                    builder.Append("\\u2028");
                    break;
                case '\u2029':
                    builder.Append("\\u2029");
                    break;
                default:
                    if (char.IsControl(character))
                    {
                        builder.Append("\\u");
                        builder.Append(((int)character).ToString("x4", CultureInfo.InvariantCulture));
                    }
                    else
                    {
                        builder.Append(character);
                    }
                    break;
            }
        }
        builder.Append('"');
        return builder.ToString();
    }

    private static string XmlText(string value)
    {
        return value
            .Replace("&", "&amp;", StringComparison.Ordinal)
            .Replace("<", "&lt;", StringComparison.Ordinal)
            .Replace(">", "&gt;", StringComparison.Ordinal);
    }
