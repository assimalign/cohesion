        builder.AppendLine("        });");
        builder.AppendLine();
        builder.AppendLine("    internal sealed class ResourceManifestDefaults");
        builder.AppendLine("    {");
        builder.AppendLine("        internal ResourceManifestDefaults(ResourceEndpointDefault[] endpoints, ResourceSettingDefault[] settings)");
        builder.AppendLine("        {");
