<#!
.SYNOPSIS
Regenerates the text tokenizer classes from checksum-pinned Unicode 17.0 data.
.DESCRIPTION
Download UnicodeData.txt from https://www.unicode.org/Public/17.0.0/ucd/ into
InputDirectory. This writes production source; changing the tables changes analyzer output.
!#>
param([Parameter(Mandatory = $true)][string] $InputDirectory)
$ErrorActionPreference = 'Stop'
$path = Join-Path $InputDirectory 'UnicodeData.txt'
if ((Get-FileHash $path -Algorithm SHA256).Hash -ne '2E1EFC1DCB59C575EEDF5CCAE60F95229F706EE6D031835247D843C11D96470C') {
    throw 'The Unicode 17.0 checksum for UnicodeData.txt does not match.'
}
$classes = [byte[]]::new(0x110000)
$first = -1
foreach ($line in Get-Content $path) {
    $fields = $line.Split(';')
    $scalar = [Convert]::ToInt32($fields[0], 16)
    $kind = if ($fields[2] -in 'Lu','Ll','Lt','Lm','Lo','Nl','Nd') { 1 } elseif ($fields[2] -in 'Mn','Mc','Me','Cf') { 2 } else { 0 }
    if ($fields[1].EndsWith(', First>')) { $first = $scalar; continue }
    $start = if ($fields[1].EndsWith(', Last>')) { $first } else { $scalar }
    for ($value = $start; $value -le $scalar; $value++) { $classes[$value] = $kind }
}
$output = [Text.StringBuilder]::new()
[void]$output.AppendLine(@'
// <auto-generated />
// Unicode 17.0.0, Unicode License v3: see docs/UNICODE_LICENSE.txt.
// Reproduce with scripts/resources/Database/Generate-TextTokenizerData.ps1.
// Output changes require an analyzer version decision; no runtime categories are used.
using System;

namespace Assimalign.Cohesion.Database.Text.Internal;

internal static class TextUnicodeData
{
'@)
foreach ($kind in 1,2) {
    $name = if ($kind -eq 1) { '_wordRanges' } else { '_continuationRanges' }
    [void]$output.AppendLine("    private static readonly int[] $name =")
    [void]$output.AppendLine('    [')
    $start = -1
    for ($scalar = 0; $scalar -le $classes.Length; $scalar++) {
        $included = $scalar -lt $classes.Length -and $classes[$scalar] -eq $kind
        if ($included -and $start -lt 0) { $start = $scalar }
        if (!$included -and $start -ge 0) {
            [void]$output.AppendLine(('        0x{0:X}, 0x{1:X},' -f $start,($scalar - 1)))
            $start = -1
        }
    }
    [void]$output.AppendLine("    ];`n")
}
[void]$output.AppendLine(@'
    internal static bool IsLetterOrDigit(int scalar) => Contains(_wordRanges, scalar);

    internal static bool IsContinuation(int scalar) => Contains(_continuationRanges, scalar);

    private static bool Contains(ReadOnlySpan<int> ranges, int scalar)
    {
        int low = 0, high = ranges.Length / 2 - 1;
        while (low <= high)
        {
            int middle = (low + high) / 2;
            if (scalar < ranges[middle * 2])
            {
                high = middle - 1;
            }
            else if (scalar > ranges[middle * 2 + 1])
            {
                low = middle + 1;
            }
            else
            {
                return true;
            }
        }

        return false;
    }
}
'@)
$repository = [IO.Path]::GetFullPath("$PSScriptRoot/../../..")
$destination = Join-Path $repository 'resources/Database/Assimalign.Cohesion.Database.Text/src/Internal/TextUnicodeData.Generated.cs'
[IO.File]::WriteAllText($destination,($output.ToString() -replace '\r?\n',"`r`n"),[Text.UTF8Encoding]::new($false))
Write-Output 'Generated Unicode 17.0 word and continuation ranges.'
