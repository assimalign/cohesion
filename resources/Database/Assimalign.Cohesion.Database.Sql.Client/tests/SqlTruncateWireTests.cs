using System;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;

using Shouldly;
using Xunit;

namespace Assimalign.Cohesion.Database.Sql.Client.Tests;

public sealed class SqlTruncateWireTests
{
    [Theory(DisplayName = "Cohesion Test [Sql.Client] - TRUNCATE: FK lists, identity policies, snapshots and refusals survive both transports")]
    [InlineData(false)]
    [InlineData(true)]
    public async Task ExecuteAsync_TruncatePolicies_ShouldPreserveWireSnapshotsAndConnection(bool tcp)
    {
        // Arrange
        using var timeout = new CancellationTokenSource(TimeSpan.FromSeconds(30));
        await using var harness = await SqlClientTestHarness.StartAsync(tcp: tcp);
        await using var writer = await harness.Client.ConnectAsync(timeout.Token);
        await writer.ExecuteAsync("CREATE TABLE p (id BIGINT GENERATED BY DEFAULT AS IDENTITY (START 10 INCREMENT 3) PRIMARY KEY)", cancellationToken: timeout.Token);
        await writer.ExecuteAsync("CREATE TABLE c (id INT PRIMARY KEY, pid BIGINT REFERENCES p(id))", cancellationToken: timeout.Token);
        await writer.ExecuteAsync("INSERT INTO p DEFAULT VALUES", cancellationToken: timeout.Token);
        await writer.ExecuteAsync("INSERT INTO c VALUES (1,10)", cancellationToken: timeout.Token);
        await using var reader = await harness.Client.ConnectAsync(timeout.Token);
        await reader.ExecuteAsync("BEGIN", cancellationToken: timeout.Token);
        (await reader.QueryAsync("SELECT * FROM c", cancellationToken: timeout.Token)).Single()[1].ShouldBe(10L);

        // Act / Assert: a restrict failure and a missing list member preserve both tables.
        var restrict = await Should.ThrowAsync<SqlClientException>(async () =>
            await writer.ExecuteAsync("TRUNCATE p RESTRICT", cancellationToken: timeout.Token));
        restrict.Diagnostics.ShouldHaveSingleItem().Code.ShouldBe("CS03067");
        restrict.ConnectionUsable.ShouldBeTrue();
        await Should.ThrowAsync<SqlClientException>(async () =>
            await writer.ExecuteAsync("TRUNCATE p, absent CASCADE", cancellationToken: timeout.Token));
        (await writer.ExecuteAsync("TRUNCATE TABLE ONLY p, c CONTINUE IDENTITY RESTRICT", cancellationToken: timeout.Token)).ShouldBe(0);
        (await writer.QueryAsync("SELECT * FROM p", cancellationToken: timeout.Token)).ShouldBeEmpty();
        (await writer.QueryAsync("SELECT * FROM c", cancellationToken: timeout.Token)).ShouldBeEmpty();
        (await reader.QueryAsync("SELECT * FROM p WHERE id=10", cancellationToken: timeout.Token)).Single()[0].ShouldBe(10L);
        (await reader.QueryAsync("SELECT * FROM c", cancellationToken: timeout.Token)).Single()[1].ShouldBe(10L);
        var refused = await Should.ThrowAsync<SqlClientException>(async () =>
            await reader.ExecuteAsync("TRUNCATE c", cancellationToken: timeout.Token));
        refused.Diagnostics.ShouldHaveSingleItem().Code.ShouldBe("CS04066");
        refused.ConnectionUsable.ShouldBeTrue();
        await reader.ExecuteAsync("ROLLBACK", cancellationToken: timeout.Token);
        await writer.ExecuteAsync("INSERT INTO p DEFAULT VALUES", cancellationToken: timeout.Token);
        (await writer.QueryAsync("SELECT * FROM p", cancellationToken: timeout.Token)).Single()[0].ShouldBe(13L);
        await writer.ExecuteAsync("TRUNCATE p RESTART IDENTITY CASCADE", cancellationToken: timeout.Token);
        await writer.ExecuteAsync("INSERT INTO p DEFAULT VALUES", cancellationToken: timeout.Token);
        (await writer.QueryAsync("SELECT * FROM p", cancellationToken: timeout.Token)).Single()[0].ShouldBe(10L);
        await Should.ThrowAsync<SqlClientException>(async () =>
            await writer.ExecuteAsync("CREATE TABLE ctas AS SELECT 1", cancellationToken: timeout.Token));
        (await writer.QueryAsync("SELECT COUNT(*) FROM p", cancellationToken: timeout.Token)).Single()[0].ShouldBe(1L);
    }
}
