using System.Collections.Generic;
using System.Linq;

using Shouldly;
using Xunit;

using Assimalign.Cohesion.Database.Types;

namespace Assimalign.Cohesion.Database.Sql.Language.Tests;

public sealed class SqlIdentityParserTests
{
    public static IEnumerable<object[]> Definitions()
    {
        foreach (string prefix in new[] { "CREATE TABLE t (id BIGINT ", "ALTER TABLE t ADD COLUMN id BIGINT " })
        {
            foreach (var (clause, always, start, increment) in new (string, bool, long, long)[]
            {
                ("GENERATED ALWAYS AS IDENTITY", true, 1, 1),
                ("GENERATED BY DEFAULT AS IDENTITY", false, 1, 1),
                ("GENERATED ALWAYS AS IDENTITY (START WITH 100 INCREMENT BY 5)", true, 100, 5),
                ("GENERATED BY DEFAULT AS IDENTITY (START 8 INCREMENT -2)", false, 8, -2),
                ("GENERATED ALWAYS AS IDENTITY (INCREMENT BY -1)", true, -1, -1),
                ("GENERATED ALWAYS AS IDENTITY (START WITH -9223372036854775808 INCREMENT BY 9223372036854775807)", true, long.MinValue, long.MaxValue),
                ("IDENTITY", true, 1, 1), ("IDENTITY(1,1)", true, 1, 1), ("IDENTITY(100, 5)", true, 100, 5),
            })
            {
                yield return [prefix + clause + (prefix.StartsWith("CREATE") ? ");" : ";"), always, start, increment];
            }
        }
    }

    [Theory(DisplayName = "Cohesion Test [Sql.Language] - Identity: canonical and lexical forms retain their facet")]
    [MemberData(nameof(Definitions))]
    public void Parse_IdentityDefinition_ShouldRetainFacet(string sql, bool always, long start, long increment)
    {
        // Arrange / Act
        var statement = new SqlQueryParser().Parse(sql).ShouldBeOfType<SqlQueryStatement>();
        var column = statement.SqlExpression is SqlCreateTableExpression create ? create.Columns.Single()
            : ((SqlAlterAddColumnAction)statement.SqlExpression.ShouldBeOfType<SqlAlterTableExpression>().Action).Column;

        // Assert
        statement.Diagnostics.ShouldBeEmpty();
        column.Identity.ShouldNotBeNull();
        column.Identity.IsAlways.ShouldBe(always);
        column.Identity.Start.ShouldBe(start);
        column.Identity.Increment.ShouldBe(increment);
        column.IsNullable.ShouldBeFalse();
    }

    [Theory(DisplayName = "Cohesion Test [Sql.Language] - Identity: contextual words remain legal column names")]
    [InlineData("identity")][InlineData("generated")][InlineData("start")][InlineData("increment")]
    public void Parse_ContextualColumnName_ShouldRemainBindable(string name)
    {
        // Arrange / Act / Assert
        foreach (string sql in new[] { $"CREATE TABLE t ({name} INT);", $"SELECT {name} FROM t;" })
        {
            new SqlQueryParser().Parse(sql).Diagnostics.ShouldBeEmpty();
        }
    }

    [Theory(DisplayName = "Cohesion Test [Sql.Language] - Identity: unsupported extensions report COHDBL001")]
    [InlineData("CREATE TABLE t (id SERIAL)", "SERIAL")]
    [InlineData("CREATE TABLE t (id BIGSERIAL)", "BIGSERIAL")]
    [InlineData("CREATE TABLE t (id SMALLSERIAL)", "SMALLSERIAL")]
    [InlineData("CREATE SEQUENCE ids", "SEQUENCE")]
    [InlineData("INSERT INTO t OVERRIDING SYSTEM VALUE VALUES (1)", "OVERRIDING")]
    [InlineData("ALTER TABLE t ALTER COLUMN id RESTART", "RESTART")]
    [InlineData("ALTER TABLE t ALTER COLUMN id SET GENERATED ALWAYS", "SET GENERATED")]
    [InlineData("CREATE TABLE t (id INT GENERATED ALWAYS AS (1) STORED)", "STORED")]
    [InlineData("CREATE TABLE t (id INT GENERATED ALWAYS AS IDENTITY (CACHE 5))", "CACHE")]
    public void Parse_ExcludedIdentityForm_ShouldReportNamedUnsupported(string sql, string form)
    {
        // Arrange / Act
        var errors = new SqlQueryParser().Parse(sql).Diagnostics.Where(item => item.Severity == DiagnosticSeverity.Error).ToArray();

        // Assert
        errors.ShouldHaveSingleItem().Code.ShouldBe("COHDBL001");
        errors[0].Message.ShouldNotBeNull().ShouldContain(form, Case.Sensitive);
        if (form.EndsWith("SERIAL")) { errors[0].Message.ShouldNotBeNull().ShouldContain("GENERATED BY DEFAULT AS IDENTITY", Case.Sensitive); }
    }

    [Theory(DisplayName = "Cohesion Test [Sql.Language] - Identity: malformed options fail total parsing")]
    [InlineData("IDENTITY(1)")][InlineData("IDENTITY(1,)")][InlineData("IDENTITY(1,1,1)")]
    [InlineData("GENERATED AS IDENTITY")][InlineData("GENERATED ALWAYS IDENTITY")]
    [InlineData("GENERATED ALWAYS AS IDENTITY (START 1 START 2)")]
    [InlineData("GENERATED ALWAYS AS IDENTITY (INCREMENT 1 INCREMENT 2)")]
    [InlineData("GENERATED ALWAYS AS IDENTITY (START 9223372036854775808)")]
    [InlineData("GENERATED ALWAYS AS IDENTITY (START 1.5)")]
    public void Parse_MalformedIdentity_ShouldReportError(string clause)
    {
        // Arrange / Act / Assert
        new SqlQueryParser().Parse($"CREATE TABLE t (id BIGINT {clause})")
            .Diagnostics.ShouldContain(item => item.Severity == DiagnosticSeverity.Error);
    }
}
