using System;
using System.Globalization;

using Assimalign.Cohesion.Database.Language;

namespace Assimalign.Cohesion.Database.Sql.Language;

public sealed partial class SqlQueryParser
{
    private SqlIdentityDefinition ParseIdentity(ref TokenLexer lexer)
    {
        bool alias = IsWord(ref lexer, "IDENTITY");
        bool always = true;
        Advance(ref lexer);
        if (!alias)
        {
            if (IsWord(ref lexer, "ALWAYS")) { Advance(ref lexer); }
            else
            {
                ExpectKeyword(ref lexer, "BY", "ALWAYS or BY DEFAULT after GENERATED");
                ExpectKeyword(ref lexer, "DEFAULT", "DEFAULT after GENERATED BY");
                always = false;
            }
            ExpectKeyword(ref lexer, "AS", "AS after the identity generation mode");
            if (lexer.Current.Type == TokenType.LeftParen)
            {
                RequireSkippedConstruct(lexer.Current.Position, lexer.Current.Position + 1, "GENERATED ALWAYS AS (expr) STORED");
                SkipParenthesized(ref lexer);
                if (IsWord(ref lexer, "STORED")) { Advance(ref lexer); }
                return new SqlIdentityDefinition(always, 1, 1);
            }
            ExpectIdentityWord(ref lexer, "IDENTITY");
        }
        long? start = null;
        long increment = 1;
        bool sawIncrement = false;
        if (lexer.Current.Type == TokenType.LeftParen)
        {
            Advance(ref lexer);
            if (alias)
            {
                start = ParseIdentityInteger(ref lexer);
                Expect(ref lexer, TokenType.Comma, "',' between IDENTITY seed and increment");
                increment = ParseIdentityInteger(ref lexer);
            }
            else
            {
                while (!IsAtEnd(ref lexer) && lexer.Current.Type is not (TokenType.RightParen or TokenType.Semicolon))
                {
                    if (IsWord(ref lexer, "START"))
                    {
                        if (start is not null) { AddSyntaxDiagnostic(ref lexer, ErrorMessages.SqlQueryParserParseIdentityVoid); }
                        Advance(ref lexer);
                        if (IsWord(ref lexer, "WITH")) { Advance(ref lexer); }
                        start = ParseIdentityInteger(ref lexer);
                    }
                    else if (IsWord(ref lexer, "INCREMENT"))
                    {
                        if (sawIncrement) { AddSyntaxDiagnostic(ref lexer, ErrorMessages.SqlQueryParserParseIdentityVoid2); }
                        sawIncrement = true;
                        Advance(ref lexer);
                        if (IsWord(ref lexer, "BY")) { Advance(ref lexer); }
                        increment = ParseIdentityInteger(ref lexer);
                    }
                    else if (IsWord(ref lexer, "MINVALUE") || IsWord(ref lexer, "MAXVALUE") ||
                        IsWord(ref lexer, "CYCLE") || IsWord(ref lexer, "CACHE") || IsWord(ref lexer, "NO"))
                    {
                        RequireSkippedConstruct(lexer.Current.Position, lexer.Current.Position + lexer.Current.Value.Length, "IDENTITY MINVALUE/MAXVALUE/CYCLE/CACHE");
                        SkipToColumnDefinitionEnd(ref lexer);
                        if (lexer.Current.Type == TokenType.RightParen) { Advance(ref lexer); }
                        return new SqlIdentityDefinition(always, start ?? 1, increment);
                    }
                    else
                    {
                        AddSyntaxDiagnostic(ref lexer, ErrorMessages.SqlQueryParserParseIdentityVoid3);
                        SkipToColumnDefinitionEnd(ref lexer);
                        if (lexer.Current.Type == TokenType.RightParen) { Advance(ref lexer); }
                        return new SqlIdentityDefinition(always, start ?? 1, increment);
                    }
                }
            }
            if (!alias && start is null && !sawIncrement)
            {
                AddExpectedDiagnostic(ref lexer, "START or INCREMENT in IDENTITY options");
            }
            Expect(ref lexer, TokenType.RightParen, _errorIdentityOptionsClosingExpected);
        }
        return new SqlIdentityDefinition(always, start ?? (increment < 0 ? -1 : 1), increment);
    }

    private void ExpectIdentityWord(ref TokenLexer lexer, string word)
    {
        if (IsWord(ref lexer, word)) { Advance(ref lexer); }
        else { AddExpectedDiagnostic(ref lexer, word); }
    }

    private long ParseIdentityInteger(ref TokenLexer lexer)
    {
        int start = lexer.Current.Position;
        string sign = string.Empty;
        if (CurrentText(ref lexer) is "+" or "-") { sign = CurrentText(ref lexer); Advance(ref lexer); }
        string number = CurrentText(ref lexer);
        if (number.Length > 0 && number.AsSpan().IndexOfAnyExceptInRange('0', '9') < 0 &&
            long.TryParse(sign + number, NumberStyles.AllowLeadingSign, CultureInfo.InvariantCulture, out long value))
        {
            Advance(ref lexer);
            return value;
        }
        AddSyntaxDiagnostic(start, lexer.Current.Position + lexer.Current.Value.Length, ErrorMessages.QueryParserParseIdentityIntegerVoid);
        if (!IsAtEnd(ref lexer) && lexer.Current.Type is not (TokenType.RightParen or TokenType.Comma or TokenType.Semicolon)) { Advance(ref lexer); }
        return 0;
    }

    private void RejectIdentityConstruct(ref TokenLexer lexer, string construct)
    {
        RequireSkippedConstruct(lexer.Current.Position, lexer.Current.Position + lexer.Current.Value.Length, construct);
        ConsumeRemaining(ref lexer);
    }

    // Capability scanning must not reinterpret START WITH or RESTART WITH as CTEs.
    // Only locate these clauses; recursive descent still validates every option and token.
    private static bool TrySkipIdentityOptions(ref TokenLexer lexer, string? firstToken, string? previousToken)
    {
        if (firstToken is null || (!firstToken.Equals("CREATE", StringComparison.OrdinalIgnoreCase) &&
            !firstToken.Equals("ALTER", StringComparison.OrdinalIgnoreCase))) { return false; }
        var lookahead = lexer;
        if (IsWord(ref lexer, "RESTART") && MoveTypeLookahead(ref lookahead) && IsWord(ref lookahead, "WITH"))
        {
            lexer = lookahead;
            return true;
        }
        if (previousToken?.ToUpperInvariant() is not ("AS" or "TINYINT" or "SMALLINT" or "INT" or "INTEGER" or "BIGINT" or "INT2" or "INT4" or "INT8") ||
            !IsWord(ref lexer, "IDENTITY") || !MoveTypeLookahead(ref lookahead) || lookahead.Current.Type != TokenType.LeftParen)
        {
            return false;
        }
        int depth = 1;
        while (MoveTypeLookahead(ref lookahead) && lookahead.Current.Type != TokenType.Semicolon)
        {
            if (lookahead.Current.Type == TokenType.LeftParen) { depth++; }
            if (lookahead.Current.Type == TokenType.RightParen && --depth == 0)
            {
                lexer = lookahead;
                return true;
            }
        }
        return false;
    }

    private bool TryRejectIdentityAlter(ref TokenLexer lexer)
    {
        if (!IsWord(ref lexer, "ALTER")) { return false; }
        var lookahead = lexer;
        MoveTypeLookahead(ref lookahead);
        if (IsWord(ref lookahead, "COLUMN")) { MoveTypeLookahead(ref lookahead); }
        MoveTypeLookahead(ref lookahead); // column name
        if (IsWord(ref lookahead, "RESTART"))
        {
            RejectIdentityConstruct(ref lexer, "ALTER COLUMN RESTART");
            return true;
        }
        if (IsWord(ref lookahead, "SET"))
        {
            MoveTypeLookahead(ref lookahead);
            if (IsWord(ref lookahead, "GENERATED"))
            {
                RejectIdentityConstruct(ref lexer, "ALTER COLUMN SET GENERATED");
                return true;
            }
        }
        return false;
    }
}
