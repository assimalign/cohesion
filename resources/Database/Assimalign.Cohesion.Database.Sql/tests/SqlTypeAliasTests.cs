namespace Assimalign.Cohesion.Database.Sql.Tests;

public sealed class SqlTypeAliasTests
{
    [Theory(DisplayName = "Cohesion Test [Sql] - Type aliases: built-in aliases cannot register unreachable domains")]
    [InlineData("NVARCHAR")]
    [InlineData("NCHAR")]
    [InlineData("DATETIME2")]
    [InlineData("DATETIMEOFFSET")]
    [InlineData("UNIQUEIDENTIFIER")]
    [InlineData("BIT")]
    [InlineData("SMALLDATETIME")]
    public void CreateDomain_BuiltInAlias_ShouldRejectName(string name)
    {
        // Arrange / Act / Assert
        Should.Throw<ArgumentException>(() => SqlType.CreateDomain(name, SqlType.Integer));
    }

    [Theory(DisplayName = "Cohesion Test [Sql] - SERIAL: SQL and native domains refuse shadowed names with an IDENTITY suggestion")]
    [InlineData("serial")][InlineData("bigserial")][InlineData("smallserial")]
    public async Task CreateDomain_SerialName_ShouldRefuseAtCreation(string name)
    {
        // Arrange
        await using var engine = SqlDatabaseEngine.Create("serial-names", new SqlDatabaseEngineOptions());
        var database = await engine.CreateDatabaseAsync("app", CancellationToken.None);
        await using var session = await database.CreateSessionAsync(CancellationToken.None);
        ulong generation = database.Catalog.DdlGeneration;

        // Act
        var native = Should.Throw<ArgumentException>(() => SqlType.CreateDomain(name, SqlType.Integer));
        var sql = await Should.ThrowAsync<DatabaseException>(async () =>
            await session.ExecuteAsync($"CREATE DOMAIN {name} AS INT", cancellationToken: CancellationToken.None));

        // Assert
        native.Message.ShouldContain("CK00001", Case.Sensitive);
        native.Message.ShouldContain("GENERATED BY DEFAULT AS IDENTITY", Case.Sensitive);
        sql.Diagnostics.ShouldContain(item => item.Code == "CK00001");
        sql.Message.ShouldContain("GENERATED BY DEFAULT AS IDENTITY", Case.Sensitive);
        database.Catalog.DdlGeneration.ShouldBe(generation);
    }

    [Theory(DisplayName = "Cohesion Test [Sql] - Type aliases: canonical metadata, values and CAST survive wire and reopen")]
    [InlineData(false)]
    [InlineData(true)]
    public async Task ExecuteAsync_TypeNames_ShouldRoundTripCatalog(bool wire)
    {
        // Arrange: all 19 DATA_TYPE spellings, including Character added by #1437.
        string[] names = ["BOOLEAN", "TINYINT", "SMALLINT", "INTEGER", "BIGINT", "REAL", "DOUBLE PRECISION",
            "NUMERIC", "CHARACTER", "CHARACTER VARYING", "BINARY VARYING", "DATE", "TIME", "TIMESTAMP",
            "TIMESTAMP WITH TIME ZONE", "INTERVAL", "UUID", "JSON", "JSONB"];
        string root = Path.Combine(Path.GetTempPath(), "cohesion-aliases", Guid.NewGuid().ToString("N"));
        using var timeout = new CancellationTokenSource(TimeSpan.FromSeconds(60));
        try
        {
            for (int opening = 0; opening < 2; opening++)
            {
                await using var engine = SqlDatabaseEngine.Create("aliases", new SqlDatabaseEngineOptions { RootPath = root });
                var database = opening == 0 ? await engine.CreateDatabaseAsync("app", timeout.Token) : await engine.OpenDatabaseAsync("app", timeout.Token);
                await using var session = await database.CreateSessionAsync(timeout.Token);
                await using var listener = new InMemoryConnectionListener();
                await using var server = SqlDatabaseServer.Create(engine, new SqlDatabaseServerOptions { Listener = listener });
                if (wire) { await server.StartAsync(timeout.Token); }
                await using var client = SqlClient.Create(new SqlClientOptions
                {
                    Settings = new DatabaseConnectionSettings { Database = "app", Principal = "aliases", EndPoint = listener.EndPoint },
                    ConnectionFactory = listener.CreateFactory(),
                });
                await using var connection = wire ? await client.ConnectAsync(timeout.Token) : null;
                async Task ExecuteAsync(string sql)
                {
                    if (connection is not null) { await connection.ExecuteAsync(sql, cancellationToken: timeout.Token); }
                    else { (await session.ExecuteAsync(sql, cancellationToken: timeout.Token)).Status.ShouldBe(DatabaseResultStatus.Success); }
                }
                async Task<List<object?[]>> QueryAsync(string sql)
                {
                    if (connection is not null)
                    {
                        var result = await connection.QueryAsync(sql, cancellationToken: timeout.Token);
                        return result.Select(row => Enumerable.Range(0, result.Columns.Count).Select(row.GetValue).ToArray()).ToList();
                    }
                    await using var local = (await session.ExecuteAsync(sql, cancellationToken: timeout.Token)).ShouldBeAssignableTo<DatabaseResultSet>();
                    var rows = new List<object?[]>();
                    await foreach (var row in local.GetRowsAsync(timeout.Token))
                    {
                        rows.Add(Enumerable.Range(0, row.FieldCount).Select(row.GetValue).ToArray());
                    }
                    return rows;
                }
                if (opening == 0)
                {
                    await ExecuteAsync("CREATE TABLE canonical (" + string.Join(", ", names.Select((name, index) => $"c{index} {name}")) + ")");
                    await ExecuteAsync("CREATE TABLE aliases (n NCHAR(10), national NATIONAL CHARACTER(10), s NVARCHAR(MAX), b VARBINARY(MAX), d DATETIME, d2 DATETIME2, dto DATETIMEOFFSET, u UNIQUEIDENTIFIER)");
                    await ExecuteAsync("CREATE FUNCTION alias_cast(value DOUBLE PRECISION) RETURNS DOUBLE PRECISION IMMUTABLE RETURN CAST(value AS DOUBLE PRECISION)");
                    await ExecuteAsync("INSERT INTO aliases (n, national, s) VALUES ('ab', 'ab', 'text')");
                    foreach (string type in new[] { "INT(x)", "DECIMAL(99999999999)", "UNIQUEIDENTIFIER(16)", "INT(11)", "BOOLEAN(1)", "DATE(3)", "VARCHAR(0)", "FLOAT(0)", "FLOAT(54)", "DECIMAL(29,0)" })
                    {
                        // Act / Assert: each parse failure leaves this same session usable.
                        string sql = $"CREATE TABLE invalid (c {type})";
                        if (connection is not null)
                        {
                            var error = await Should.ThrowAsync<SqlClientException>(() => ExecuteAsync(sql));
                            error.Code.ShouldBe(ProtocolErrorCode.ParseFailure);
                            error.ConnectionUsable.ShouldBeTrue();
                            error.Message.ShouldContain("SQL0005", Case.Sensitive);
                        }
                        else
                        {
                            (await Should.ThrowAsync<DatabaseParseException>(() => ExecuteAsync(sql))).Message.ShouldContain("SQL0005", Case.Sensitive);
                        }
                    }
                    await ExecuteAsync("INSERT INTO aliases (s) VALUES ('after failures')");
                }

                // Act / Assert: each ISO name reads back with all modifier metadata.
                var metadata = await QueryAsync("SELECT DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, NUMERIC_PRECISION, NUMERIC_SCALE, DATETIME_PRECISION FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'canonical' ORDER BY ORDINAL_POSITION");
                metadata.Count.ShouldBe(names.Length);
                long?[] precision = [null, 8, 16, 32, 64, 24, 53, null, null, null, null, null, null, null, null, null, null, null, null];
                for (int index = 0; index < names.Length; index++)
                {
                    metadata[index].ShouldBe(new object?[] { names[index], index == 8 ? 1L : null, precision[index],
                        index is >= 1 and <= 4 ? 0L : null, index == 11 ? 0L : index is >= 12 and <= 14 ? 7L : null });
                }
                var aliasMetadata = await QueryAsync("SELECT DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, DATETIME_PRECISION FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'aliases' ORDER BY ORDINAL_POSITION");
                aliasMetadata.ShouldBe(new object?[][] { ["CHARACTER", 10L, null], ["CHARACTER", 10L, null], ["CHARACTER VARYING", null, null], ["BINARY VARYING", null, null],
                    ["TIMESTAMP", null, 7L], ["TIMESTAMP", null, 7L], ["TIMESTAMP WITH TIME ZONE", null, 7L], ["UUID", null, null] });
                (await QueryAsync("SELECT n, national, CAST('ab' AS NCHAR(10)), CAST('ab' AS NATIONAL CHARACTER(10)), CAST('ab' AS NVARCHAR(MAX)), alias_cast(1.5), CAST(1 AS FLOAT(24)) FROM aliases WHERE s = 'text'"))
                    .ShouldHaveSingleItem().ShouldBe(new object?[] { "ab        ", "ab        ", "ab        ", "ab        ", "ab", 1.5d, 1f });
                (await QueryAsync("SELECT s FROM aliases WHERE s = 'after failures'")).ShouldHaveSingleItem()[0].ShouldBe("after failures");
            }
        }
        finally
        {
            if (Directory.Exists(root)) { Directory.Delete(root, true); }
        }
    }
}
