        database.IndexManager.ExportRegistrations().ShouldBeEmpty();
        await Execute(session, "INSERT INTO t VALUES(1)");
    }

    [Fact(DisplayName = "Cohesion Test [Sql] - Partial indexes: metadata, views, dependencies and query scans remain truthful (#1630)")]
    public async Task ExecuteAsync_MetadataAndDependencies_ShouldPreservePredicateAndAvoidAccess()
    {
        // Arrange
        await using var engine = SqlDatabaseEngine.Create("partial-metadata", new());
        var database = await engine.CreateDatabaseAsync("db", CancellationToken.None);
        await using var session = await database.CreateSessionAsync(CancellationToken.None);
        await Execute(session, "CREATE TABLE t(k INT,active BOOLEAN)");
        await Execute(session, "CREATE INDEX ix ON t(k) WHERE active AND k>0");
        await Execute(session, "INSERT INTO t VALUES(1,TRUE),(1,FALSE),(2,TRUE)");
        await Execute(session, "CREATE VIEW predicates AS SELECT INDEX_NAME,PREDICATE FROM INFORMATION_SCHEMA.INDEXES");
        string canonical = database.Catalog.GetIndexes(database.Catalog.Tables.Single().ObjectId).Single().Predicate!;

        // Act / Assert
        (await Rows(session, "SELECT PREDICATE FROM predicates WHERE INDEX_NAME='ix'")).Single()[0].ShouldBe(canonical);
        (await Rows(session, "SELECT PREDICATE FROM COHESION_SCHEMA.INDEXES WHERE INDEX_NAME='ix'")).Single()[0].ShouldBe(canonical);
        (await Rows(session, "SELECT k FROM t WHERE k=1")).Length.ShouldBe(2);
        session.LastStatementMetrics!.AccessPath.ShouldBe("scan");
        (await Rows(session, "EXPLAIN SELECT a.k FROM t a JOIN t b ON a.k=b.k WHERE a.k=1")).ShouldNotContain(row => Equals(row[4], "ix"));
        await Rows(session, "SELECT k FROM t WHERE k=1 AND active");
        session.LastStatementMetrics!.AccessPath.ShouldBe("scan");
        await Execute(session, "ALTER TABLE t RENAME COLUMN active TO enabled");
        await Execute(session, "ALTER TABLE t RENAME TO renamed");
        await Execute(session, "UPDATE renamed SET enabled=TRUE");
        await Refuses(session, "ALTER TABLE renamed ALTER COLUMN enabled TYPE INT USING CASE WHEN enabled THEN 1 ELSE 0 END", "CS03083");
        await Execute(session, "ALTER TABLE renamed DROP COLUMN enabled");
        database.Catalog.GetIndexes(database.Catalog.Tables.Single().ObjectId).ShouldBeEmpty();
        database.IndexManager.ExportRegistrations().ShouldBeEmpty();
    }

    [Fact(DisplayName = "Cohesion Test [Sql] - Partial indexes: cascade lookup scans rows outside the predicate (#1630)")]
    public async Task ExecuteAsync_CascadeOutsidePredicate_ShouldMaintainAllRows()
    {
        // Arrange
        await using var engine = SqlDatabaseEngine.Create("partial-cascade", new());
        var database = await engine.CreateDatabaseAsync("db", CancellationToken.None);
        await using var session = await database.CreateSessionAsync(CancellationToken.None);
        await Execute(session, "CREATE TABLE p(id INT PRIMARY KEY)");
        await Execute(session, "CREATE TABLE c(id INT,pid INT REFERENCES p(id) ON UPDATE CASCADE ON DELETE CASCADE,active BOOLEAN)");
        await Execute(session, "CREATE INDEX ix ON c(pid) WHERE active");
        await Execute(session, "INSERT INTO p VALUES(1)");
        await Execute(session, "INSERT INTO c VALUES(1,1,FALSE),(2,1,TRUE)");

        // Act / Assert
        await Oracle(database, session, "c", "pid", "active");
        await Execute(session, "UPDATE p SET id=2");
        (await Rows(session, "SELECT pid FROM c ORDER BY id")).ShouldBe([[2],[2]]);
        await Oracle(database, session, "c", "pid", "active");
        await Execute(session, "DELETE FROM p");
        (await Rows(session, "SELECT * FROM c")).ShouldBeEmpty();
        await Oracle(database, session, "c", "pid", "active");
        await Execute(session, "DROP TABLE c");
        await Execute(session, "INSERT INTO p VALUES(1),(2)");
        await Execute(session, "CREATE TABLE c(id INT,pid INT DEFAULT 1 REFERENCES p(id) ON UPDATE SET NULL ON DELETE SET DEFAULT)");
        await Execute(session, "CREATE INDEX ix ON c(pid) WHERE pid IS NULL");
        await Execute(session, "INSERT INTO c VALUES(1,2),(2,2)");
        await Execute(session, "UPDATE p SET id=20 WHERE id=2");
        await Oracle(database, session, "c", "pid", "pid IS NULL");
        await Execute(session, "UPDATE c SET pid=20");
        await Oracle(database, session, "c", "pid", "pid IS NULL");
        await Execute(session, "DROP INDEX ix ON c");
        await Execute(session, "CREATE INDEX ix ON c(pid) WHERE pid=1");
        await Execute(session, "DELETE FROM p WHERE id=20");
        await Oracle(database, session, "c", "pid", "pid=1");
    }

    [Fact(DisplayName = "Cohesion Test [Sql] - Partial indexes: immutable function identities and built-in casts survive maintenance (#1630)")]
    public async Task ExecuteAsync_FunctionPredicate_ShouldPinDependenciesAndRejectStableCalls()
    {
        // Arrange
        await using var engine = SqlDatabaseEngine.Create("partial-functions", new());
        var database = await engine.CreateDatabaseAsync("db", CancellationToken.None);
        await using var session = await database.CreateSessionAsync(CancellationToken.None);
        await Execute(session, "CREATE TABLE t(id INT,k INT,active BOOLEAN)");
        await Execute(session, "CREATE FUNCTION positive(k INT) RETURNS BOOLEAN IMMUTABLE RETURN k>0");
        await Execute(session, "CREATE FUNCTION stable_test(k INT) RETURNS BOOLEAN STABLE RETURN k>0");
        await Execute(session, "INSERT INTO t VALUES(1,1,TRUE),(2,-1,TRUE)");

        // Act / Assert
        await Refuses(session, "CREATE INDEX bad ON t(k) WHERE stable_test(k)", "CS05091");
        await Execute(session, "CREATE INDEX ix ON t(k) WHERE positive(CAST(k AS INT)) AND active");
        await Refuses(session, "DROP FUNCTION positive(INT)", "CS03302");
        await Execute(session, "UPDATE t SET k=2 WHERE id=2");
        (await Rows(session, "SELECT k FROM t WHERE positive(k) AND active")).Length.ShouldBe(2);
        await Execute(session, "DROP INDEX ix ON t");
        await Execute(session, "DROP FUNCTION positive(INT)");
    }

    [Fact(DisplayName = "Cohesion Test [Sql] - Partial indexes: compiled predicates validate before apply and changing them rebuilds the tree (#1630)")]
    public async Task ApplySchemaAsync_PredicateChange_ShouldRebuildAndVerifyCanonicalMetadata()
    {
        // Arrange
        await using var engine = SqlDatabaseEngine.Create("partial-schema", new());
        var database = await engine.CreateDatabaseAsync("app", CancellationToken.None);
        SqlCompiledSchema Schema(string predicate, string name = "app") => new(SqlCompiledSchema.CurrentFormat, name, true, [],
            [new("t", "Tests:Row", [new("k", DatabaseType.Int32, true), new("active", DatabaseType.Boolean, true)], null,
                [new("ix", ["k"], false, predicate)], [])], []);
        var before = Schema("active AND k>0");
        await database.ApplySchemaAsync(before, CancellationToken.None);
        await using var session = await database.CreateSessionAsync(CancellationToken.None);
        await Execute(session, "INSERT INTO t VALUES(1,TRUE),(-1,TRUE),(2,FALSE)");
        var after = Schema("active AND k > -2");

        // Act
        var changed = await database.ApplySchemaAsync(after, CancellationToken.None);
        await database.VerifySchemaAsync(after, CancellationToken.None);
        var repeat = await database.ApplySchemaAsync(after, CancellationToken.None);

        // Assert
        changed.OperationCount.ShouldBe(2);
        repeat.WasAlreadyApplied.ShouldBeTrue();
        database.Catalog.TryGetTable("dbo", "t", out var table).ShouldBeTrue();
        database.Catalog.GetIndexes(table.ObjectId).ShouldHaveSingleItem().Predicate.ShouldBe("active AND k > -2");
        var empty = await engine.CreateDatabaseAsync("invalid", CancellationToken.None);
        await Should.ThrowAsync<DatabaseException>(async () => await empty.ApplySchemaAsync(Schema("EXISTS(SELECT 1)", "invalid"), CancellationToken.None));
        empty.Catalog.Tables.ShouldBeEmpty();
    }

    internal static async Task Oracle(SqlDatabase database, SqlDatabaseSession session, string tableName = "t",
        string keyColumn = "k", string predicate = "active AND k IS NOT NULL")
    {
        var expected = (await Rows(session, $"SELECT id,{keyColumn} FROM {tableName} WHERE {predicate} ORDER BY id"))
            .Select(row => (Convert.ToInt64(row[0]), Convert.ToInt32(row[1]))).ToArray();
        database.Catalog.TryGetTable("dbo", tableName, out var table).ShouldBeTrue();
        var metadata = database.Catalog.GetIndexes(table.ObjectId).Single(index => index.Name == "ix");
        database.IndexManager.TryGetIndex(table.ObjectId, "ix", out var index).ShouldBeTrue();
        await using var reader = await database.CreateSessionAsync(CancellationToken.None);
        await using var transaction = await reader.BeginTransactionAsync(IsolationLevel.Snapshot, CancellationToken.None);
        var actual = new List<(long, int)>();
        await using (var cursor = index.OpenCursor(transaction.Context, IndexKeyRange.All))
        {
            while (await cursor.MoveNextAsync(CancellationToken.None))
            {
                var (page, slot) = SqlRecordLocation.Unpack(cursor.CurrentEntryReference);
                database.DataStorage.TryReadRecord(page, slot, table.ObjectId, out var record).ShouldBeTrue();
                var values = SqlRowCodec.Decode(record.Span, table, out _, out _, out _);
                var key = new DatabaseKeyWriter();
                foreach (string name in metadata.ColumnNames)
                {
                    int ordinal = Enumerable.Range(0, table.Columns.Count).Single(i => table.Columns[i].Name == name);
                    SqlRowCodec.AppendKeyValue(key, table.Columns[ordinal].Type.Type, values[ordinal],
                        table.Columns[ordinal].Collation ?? database.Catalog.DefaultCollation);
                }
                cursor.CurrentKey.Encoded.ToArray().ShouldBe(key.ToArray());
                actual.Add((Convert.ToInt64(values[0]), Convert.ToInt32(values[1])));
            }
        }
        actual.OrderBy(row => row.Item1).ShouldBe(expected);
        await transaction.RollbackAsync(CancellationToken.None);
    }

    internal static async Task Execute(SqlDatabaseSession session, string sql)
        => (await session.ExecuteAsync(sql, cancellationToken: CancellationToken.None)).Status.ShouldBe(DatabaseResultStatus.Success);

    internal static async Task<object?[][]> Rows(SqlDatabaseSession session, string sql)
    {
        await using var result = (await session.ExecuteAsync(sql, cancellationToken: CancellationToken.None)).ShouldBeAssignableTo<DatabaseResultSet>();
        var rows = new List<object?[]>();
        await foreach (var row in result.GetRowsAsync(CancellationToken.None))
        { rows.Add(Enumerable.Range(0, row.FieldCount).Select(row.GetValue).ToArray()); }
        return rows.ToArray();
    }

    internal static async Task Refuses(SqlDatabaseSession session, string sql, string code)
    {
        var failure = await Should.ThrowAsync<DatabaseException>(() => Execute(session, sql));
        failure.Diagnostics.ShouldContain(d => d.Code == code, string.Join("; ", failure.Diagnostics.Select(d => d.Code + ": " + d.Message)));
    }
