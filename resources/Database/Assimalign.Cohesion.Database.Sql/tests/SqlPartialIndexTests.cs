    [Theory(DisplayName = "Cohesion Test [Sql] - Partial indexes: generated DML maintains exactly the full-scan subset on every write path (#1630)")]
    [InlineData(1630)]
    [InlineData(20261029)]
    public async Task ExecuteAsync_GeneratedDml_ShouldMatchPredicateScan(int seed)
    {
        // Arrange
        await using var engine = SqlDatabaseEngine.Create("partial-oracle", new());
        var database = await engine.CreateDatabaseAsync("db", CancellationToken.None);
        await using var session = await database.CreateSessionAsync(CancellationToken.None);
        await Execute(session, "CREATE TABLE t(id INT PRIMARY KEY,k INT,active BOOLEAN)");
        await Execute(session, "INSERT INTO t VALUES(0,4,TRUE),(1,4,FALSE),(2,NULL,TRUE),(3,5,NULL)");
        await Execute(session, "CREATE INDEX ix ON t(k) WHERE active AND k IS NOT NULL");
        var random = new Random(seed);
        await Oracle(database, session);

        // Act / Assert: every operation is independently compared with a table scan.
        for (int step = 0; step < 96; step++)
        {
            int id = random.Next(16), k = random.Next(5);
            string active = step % 3 == 0 ? "NULL" : step % 2 == 0 ? "TRUE" : "FALSE";
            string sql = (step % 8) switch
            {
                0 => $"INSERT INTO t VALUES({id},{k},{active}) ON CONFLICT(id) DO NOTHING",
                1 => $"UPDATE t SET active={active},k={k} WHERE id={id}",
                2 => $"UPDATE t SET active=s.a,k=s.k FROM (SELECT {id} AS id,{active} AS a,{k} AS k) s WHERE t.id=s.id",
                3 => $"INSERT INTO t VALUES({id},{k},{active}) ON CONFLICT(id) DO UPDATE SET active=excluded.active,k=excluded.k",
                4 => $"MERGE INTO t USING (SELECT {id} AS id,{k} AS k,{active} AS a) s ON t.id=s.id WHEN MATCHED THEN UPDATE SET k=s.k,active=s.a WHEN NOT MATCHED THEN INSERT VALUES(s.id,s.k,s.a)",
                5 => $"DELETE FROM t USING (SELECT {id} AS id) s WHERE t.id=s.id",
                6 => $"DELETE FROM t WHERE id={id}",
                _ => $"INSERT INTO t SELECT {id},{k},{active} WHERE NOT EXISTS(SELECT id FROM t WHERE id={id})",
            };
            await Execute(session, sql);
            await Oracle(database, session);
        }
        await Execute(session, "ALTER TABLE t ALTER COLUMN id TYPE BIGINT");
        await Oracle(database, session);
        await Execute(session, "ALTER TABLE t ADD COLUMN serial_id INT GENERATED BY DEFAULT AS IDENTITY");
        await Oracle(database, session);
        await Execute(session, "TRUNCATE TABLE t");
        await Oracle(database, session);
        await Execute(session, "INSERT INTO t(id,k,active) VALUES(1,2,TRUE),(2,2,FALSE)");
        await Oracle(database, session);
    }

    [Fact(DisplayName = "Cohesion Test [Sql] - Partial uniqueness: only matching non-NULL keys conflict, including predicate transitions (#1630)")]
    public async Task ExecuteAsync_UniqueSubset_ShouldRejectEnteringConflictsAndAllowNulls()
    {
        // Arrange
        await using var engine = SqlDatabaseEngine.Create("partial-unique", new());
        var database = await engine.CreateDatabaseAsync("db", CancellationToken.None);
        await using var session = await database.CreateSessionAsync(CancellationToken.None);
        await Execute(session, "CREATE TABLE t(id INT PRIMARY KEY,k INT,active BOOLEAN)");
        await Execute(session, "INSERT INTO t VALUES(1,7,TRUE),(2,7,FALSE),(3,7,NULL),(4,NULL,TRUE),(5,NULL,TRUE)");
        await Execute(session, "CREATE UNIQUE INDEX uq ON t(k) WHERE active");

        // Act / Assert
        foreach (string sql in new[] {
            "INSERT INTO t VALUES(6,7,TRUE)",
            "UPDATE t SET active=TRUE WHERE id=2",
            "UPDATE t SET active=s.a FROM (SELECT 2 AS id,TRUE AS a) s WHERE t.id=s.id",
            "INSERT INTO t VALUES(2,7,TRUE) ON CONFLICT(id) DO UPDATE SET active=excluded.active",
            "MERGE INTO t USING (SELECT 2 AS id) s ON t.id=s.id WHEN MATCHED THEN UPDATE SET active=TRUE" })
        { await SqlConstraintAssertions.ThrowAsync(async () => await Execute(session, sql)); }
        await Execute(session, "INSERT INTO t VALUES(6,NULL,TRUE),(7,7,FALSE)");
        await Execute(session, "UPDATE t SET active=FALSE WHERE id=1");
        await Execute(session, "UPDATE t SET active=TRUE WHERE id=2");
        await Execute(session, "INSERT INTO t VALUES(8,7,FALSE) ON CONFLICT DO NOTHING");
        await Execute(session, "UPDATE t SET active=FALSE WHERE id=4");
        await Execute(session, "UPDATE t SET k=9 WHERE id=5");
        await Execute(session, "DELETE FROM t WHERE id=6");
        await Refuses(session, "INSERT INTO t VALUES(9,7,TRUE) ON CONFLICT(k) DO NOTHING", "CS03035");
        await SqlConstraintAssertions.ThrowAsync(async () => await Execute(session, "INSERT INTO t VALUES(9,7,TRUE) ON CONFLICT DO NOTHING"));
        await Refuses(session, "CREATE TABLE child(k INT REFERENCES t(k))", "CS03054");
        await Execute(session, "BEGIN");
        await Execute(session, "UPDATE t SET active=FALSE WHERE id=2");
        await Execute(session, "INSERT INTO t VALUES(9,7,TRUE)");
        await Execute(session, "ROLLBACK");
        await SqlConstraintAssertions.ThrowAsync(async () => await Execute(session, "INSERT INTO t VALUES(9,7,TRUE)"));
        await Execute(session, "INSERT INTO t VALUES(10,NULL,TRUE),(11,NULL,TRUE)");
        await Execute(session, "ALTER TABLE t ALTER COLUMN k TYPE BIGINT");
        await SqlConstraintAssertions.ThrowAsync(async () => await Execute(session, "INSERT INTO t VALUES(12,7,TRUE)"));
        await Execute(session, "INSERT INTO t VALUES(12,NULL,TRUE)");
        await Execute(session, "DELETE FROM t WHERE id=10");
    }

    [Theory(DisplayName = "Cohesion Test [Sql] - Partial indexes: prohibited predicates fail before build (#1630)")]
    [InlineData("$1 = 1", "CS05091")]
    [InlineData("EXISTS(SELECT 1)", "CS05091")]
    [InlineData("k IN (SELECT 1)", "CS05091")]
    [InlineData("COUNT(k) > 0", "CS05091")]
    [InlineData("ROW_NUMBER() OVER () > 0", "CS05091")]
    [InlineData("CURRENT_TIMESTAMP IS NOT NULL", "CS05091")]
    [InlineData("GEN_RANDOM_UUID() IS NOT NULL", "CS05091")]
    [InlineData("NEXT VALUE FOR s > 0", "CS05091")]
    [InlineData("nextval('s') > 0", "CS05091")]
    [InlineData("missing > 0", "CS01015")]
    [InlineData("other.k > 0", "CS01015")]
    [InlineData("k", "CS02003")]
    public async Task ExecuteAsync_InvalidPredicate_ShouldRefuseWithoutIndex(string predicate, string code)
    {
        // Arrange
        await using var engine = SqlDatabaseEngine.Create("partial-validation", new());
        var database = await engine.CreateDatabaseAsync("db", CancellationToken.None);
        await using var session = await database.CreateSessionAsync(CancellationToken.None);
