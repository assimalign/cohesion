    [Theory(DisplayName = "Cohesion Test [SqlEngine] - Upsert: defaulted proposals arbitrate against the latest committed or rolled-back key owner")]
    [InlineData(IsolationLevel.Snapshot, false)]
    [InlineData(IsolationLevel.Snapshot, true)]
    [InlineData(IsolationLevel.ReadCommitted, false)]
    [InlineData(IsolationLevel.ReadCommitted, true)]
    public Task ExecuteAsync_DefaultedContendedKey_ShouldFollowWinnerAndIsolation(IsolationLevel isolation, bool rollback)
        => RepeatAsync(async () =>
        {
            // Arrange
            using var timeout = new CancellationTokenSource(TimeSpan.FromSeconds(15));
            await using var engine = SqlDatabaseEngine.Create("upsert-default-latest", new());
            var database = await engine.CreateDatabaseAsync("app", timeout.Token);
            await using var first = await database.CreateSessionAsync(timeout.Token);
            await using var second = await database.CreateSessionAsync(timeout.Token);
            await first.ExecuteAsync("CREATE TABLE t (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, k INT UNIQUE, v INT)", cancellationToken: timeout.Token);
            await using var winner = await first.BeginTransactionAsync(isolation, timeout.Token);
            await first.ExecuteAsync("INSERT INTO t(k, v) VALUES (101, 10)", cancellationToken: timeout.Token);
            await using var contender = await second.BeginTransactionAsync(isolation, timeout.Token);
            using var waits = new LockWaitListener(database.Name);
            var pending = second.ExecuteAsync("INSERT INTO t(k, v) VALUES (101, 1) ON CONFLICT(k) DO UPDATE SET v = t.v + EXCLUDED.v", cancellationToken: timeout.Token).AsTask();
            try
            {
                // Act: both default allocation and table IX precede the observable key wait.
                await waits.WaitForWaitAsync(contender.Context.Sequence, timeout.Token);
                if (rollback) { await winner.RollbackAsync(timeout.Token); }
                else { await winner.CommitAsync(timeout.Token); }

                // Assert
                if (!rollback && isolation == IsolationLevel.Snapshot)
                {
                    await Should.ThrowAsync<DatabaseTransactionAbortedException>(async () => await pending);
                    await contender.RollbackAsync(timeout.Token);
                }
                else
                {
                    (await pending).AffectedCount.ShouldBe(1);
                    await contender.CommitAsync(timeout.Token);
                }
                (await RowsAsync(first, "SELECT id, k, v FROM t")).ShouldHaveSingleItem().ShouldBe(
                    new object?[] { rollback ? 2 : 1, 101, rollback ? 1 : isolation == IsolationLevel.Snapshot ? 10 : 11 });
            }
            finally
            {
                if (winner.Context.State == TransactionState.Active) { await winner.RollbackAsync(CancellationToken.None); }
                try { await pending; }
                catch (DatabaseTransactionAbortedException) when (!rollback && isolation == IsolationLevel.Snapshot) { }
            }
        });

    [Theory(DisplayName = "Cohesion Test [SqlEngine] - Upsert: an identity default permits an independent upsert or plain INSERT during its statement")]
    [InlineData(false)]
    [InlineData(true)]
    public Task ExecuteAsync_DefaultedSingleRow_ShouldPermitIndependentWriter(bool plainInsert)
        => RepeatAsync(async () =>
        {
            // Arrange: gate after identity allocation, outside the database apply gate.
            using var timeout = new CancellationTokenSource(TimeSpan.FromSeconds(15));
            await using var engine = SqlDatabaseEngine.Create("upsert-default-concurrency", new());
            var database = await engine.CreateDatabaseAsync("app", timeout.Token);
            await using var first = await database.CreateSessionAsync(timeout.Token);
            await using var second = await database.CreateSessionAsync(timeout.Token);
            await first.ExecuteAsync("CREATE TABLE t (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, k INT UNIQUE)", cancellationToken: timeout.Token);
            database.Catalog.TryGetTable("dbo", "t", out var table).ShouldBeTrue();
            var gate = await database.Coordinator.BeginAsync(IsolationLevel.ReadCommitted, timeout.Token);
            await database.Coordinator.LockManager.AcquireAsync(gate.Sequence,
                LockResource.Entry(table.ObjectId, Key(101).Hash()), LockMode.Exclusive, timeout.Token);
            await using var transaction = await first.BeginTransactionAsync(IsolationLevel.ReadCommitted, timeout.Token);
            using var waits = new LockWaitListener(database.Name);
            var pending = first.ExecuteAsync("INSERT INTO t(k) VALUES (101) ON CONFLICT(k) DO UPDATE SET k = EXCLUDED.k", cancellationToken: timeout.Token).AsTask();
            try
            {
                await waits.WaitForWaitAsync(transaction.Context.Sequence, timeout.Token);

                // Act: the independent writer must commit while the first statement stays gated.
                var result = await second.ExecuteAsync("INSERT INTO t(k) VALUES (202)" +
                    (plainInsert ? "" : " ON CONFLICT(k) DO UPDATE SET k = EXCLUDED.k"), cancellationToken: timeout.Token);

                // Assert
                result.AffectedCount.ShouldBe(1);
                pending.IsCompleted.ShouldBeFalse();
                (await RowsAsync(second, "SELECT id, k FROM t")).ShouldHaveSingleItem().ShouldBe(new object?[] { 2, 202 });
                await database.Coordinator.RollbackAsync(gate, timeout.Token);
                (await pending).AffectedCount.ShouldBe(1);
                await transaction.CommitAsync(timeout.Token);
                (await RowsAsync(second, "SELECT id, k FROM t ORDER BY k")).Select(row => row[0]).ShouldBe(new object?[] { 1, 2 });
            }
            finally
            {
                if (gate.State == TransactionState.Active) { await database.Coordinator.RollbackAsync(gate, CancellationToken.None); }
                await pending;
            }
        });

    [Theory(DisplayName = "Cohesion Test [SqlEngine] - Upsert: constant and immutable expression defaults retain the complete sorted proposal batch")]
    [InlineData("7")]
    [InlineData("(2 + 5)")]
    [InlineData("(ABS(-7) + 0)")]
    public Task ExecuteAsync_ImmutableDefault_ShouldLockEveryProposalInOneSortedBatch(string defaultExpression)
        => RepeatAsync(async () =>
        {
            // Arrange: force the loaded expression tree rather than its DDL-time constant.
            using var timeout = new CancellationTokenSource(TimeSpan.FromSeconds(15));
            await using var engine = SqlDatabaseEngine.Create("upsert-default-batch", new());
            var database = await engine.CreateDatabaseAsync("app", timeout.Token);
            await using var session = await database.CreateSessionAsync(timeout.Token);
            await session.ExecuteAsync($"CREATE TABLE t (k INT PRIMARY KEY, v INT DEFAULT {defaultExpression})", cancellationToken: timeout.Token);
            await session.ExecuteAsync("CREATE FUNCTION refresh_defaults(x INT) RETURNS INT IMMUTABLE RETURN x", cancellationToken: timeout.Token);
            database.Catalog.TryGetTable("dbo", "t", out var table).ShouldBeTrue();
            int[] keys = Enumerable.Range(101, 20).OrderBy(value => Key(value).Hash()).ToArray();
            int low = keys[0], high = keys[^1];
            var gate = await database.Coordinator.BeginAsync(IsolationLevel.ReadCommitted, timeout.Token);
            await database.Coordinator.LockManager.AcquireAsync(gate.Sequence,
                LockResource.Entry(table.ObjectId, Key(low).Hash()), LockMode.Exclusive, timeout.Token);
            await using var transaction = await session.BeginTransactionAsync(IsolationLevel.ReadCommitted, timeout.Token);
            using var waits = new LockWaitListener(database.Name);
            var pending = session.ExecuteAsync($"INSERT INTO t(k) VALUES ({high}), ({low}) ON CONFLICT(k) DO UPDATE SET v = DEFAULT", cancellationToken: timeout.Token).AsTask();
            try
            {
                await waits.WaitForWaitAsync(transaction.Context.Sequence, timeout.Token);

                // Act: the later proposal's lower hash must queue before the first one's higher hash.
                await database.Coordinator.LockManager.AcquireAsync(gate.Sequence,
                    LockResource.Entry(table.ObjectId, Key(high).Hash()), LockMode.Exclusive, timeout.Token);

                // Assert: a per-proposal path would instead hold high and deadlock here.
                pending.IsCompleted.ShouldBeFalse();
                await database.Coordinator.RollbackAsync(gate, timeout.Token);
                (await pending).AffectedCount.ShouldBe(2);
                await transaction.CommitAsync(timeout.Token);
                (await RowsAsync(session, "SELECT v FROM t")).Select(row => row[0]).ShouldBe(new object?[] { 7, 7 });
            }
            finally
            {
                if (gate.State == TransactionState.Active) { await database.Coordinator.RollbackAsync(gate, CancellationToken.None); }
                await pending;
            }
        });

    [Fact(DisplayName = "Cohesion Test [SqlEngine] - Upsert: reversed defaulted proposal orders detect a deadlock victim and permit a complete retry")]
    public Task ExecuteAsync_DefaultedReversedKeys_ShouldDetectDeadlockAndPermitRetry()
        => RepeatAsync(async () =>
        {
            // Arrange: the second transaction gates the first's second proposal.
            using var timeout = new CancellationTokenSource(TimeSpan.FromSeconds(15));
            await using var engine = SqlDatabaseEngine.Create("upsert-default-cycle", new());
            var database = await engine.CreateDatabaseAsync("app", timeout.Token);
            await using var first = await database.CreateSessionAsync(timeout.Token);
            await using var second = await database.CreateSessionAsync(timeout.Token);
            await first.ExecuteAsync("CREATE TABLE t (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, k INT UNIQUE, v INT DEFAULT 0)", cancellationToken: timeout.Token);
            database.Catalog.TryGetTable("dbo", "t", out var table).ShouldBeTrue();
            await using var one = await first.BeginTransactionAsync(IsolationLevel.ReadCommitted, timeout.Token);
            await using var two = await second.BeginTransactionAsync(IsolationLevel.ReadCommitted, timeout.Token);
            await database.Coordinator.LockManager.AcquireAsync(two.Context.Sequence,
                LockResource.Entry(table.ObjectId, Key(202).Hash()), LockMode.Exclusive, timeout.Token);
            using var waits = new LockWaitListener(database.Name);
            const string reverse = "INSERT INTO t(k) VALUES (202), (101) ON CONFLICT(k) DO UPDATE SET v = t.v + 1";
            var pending = first.ExecuteAsync("INSERT INTO t(k) VALUES (101), (202) ON CONFLICT(k) DO UPDATE SET v = t.v + 1", cancellationToken: timeout.Token).AsTask();
            try
            {
                // Act: first owns 101 and waits for 202; reversed proposals close the cycle.
                await waits.WaitForWaitAsync(one.Context.Sequence, timeout.Token);
                await Should.ThrowAsync<DatabaseTransactionDeadlockException>(async () =>
                    await second.ExecuteAsync(reverse, cancellationToken: timeout.Token));
                await two.RollbackAsync(timeout.Token);
                (await pending).AffectedCount.ShouldBe(2);
                await one.CommitAsync(timeout.Token);

                // Assert: roll back/retry the whole victim transaction after the survivor commits.
                await using var retry = await second.BeginTransactionAsync(IsolationLevel.ReadCommitted, timeout.Token);
                (await second.ExecuteAsync(reverse, cancellationToken: timeout.Token)).AffectedCount.ShouldBe(2);
                await retry.CommitAsync(timeout.Token);
                (await RowsAsync(second, "SELECT k, v FROM t ORDER BY k")).Select(row => row[0]).ShouldBe(new object?[] { 101, 202 });
                (await RowsAsync(second, "SELECT v FROM t")).Select(row => row[0]).ShouldBe(new object?[] { 1, 1 });
            }
            finally
            {
                if (two.Context.State == TransactionState.Active) { await two.RollbackAsync(CancellationToken.None); }
                await pending;
            }
        });

    private static IndexKey Key(int value)
    {
        var writer = new DatabaseKeyWriter();
        SqlRowCodec.AppendKeyValue(writer, DatabaseType.Int32, value, Collation.Binary);
        return IndexKey.From(writer);
    }

    private static async Task<List<object?[]>> RowsAsync(SqlDatabaseSession session, string sql)
    {
        await using var result = (DatabaseResultSet)await session.ExecuteAsync(sql, cancellationToken: CancellationToken.None);
        var rows = new List<object?[]>();
        await foreach (var row in result.GetRowsAsync(CancellationToken.None))
        { rows.Add(Enumerable.Range(0, row.FieldCount).Select(row.GetValue).ToArray()); }
        return rows;
    }

    private static async Task RepeatAsync(Func<Task> run)
    {
        var elapsed = Stopwatch.StartNew();
        int exercised = 0;
        do
        {
            await run();
            exercised++;
            elapsed.Elapsed.ShouldBeLessThan(TimeSpan.FromSeconds(45));
        }
        while (elapsed.Elapsed < TimeSpan.FromMilliseconds(250) || exercised < 3);
        exercised.ShouldBeGreaterThanOrEqualTo(3);
    }
