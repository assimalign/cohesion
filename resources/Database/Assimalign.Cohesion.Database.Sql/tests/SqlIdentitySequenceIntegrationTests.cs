    [Theory(DisplayName = "Cohesion Test [Sql] - Serial: aliases use the declared integer sequence bounds")]
    [InlineData("SMALLSERIAL", "SMALLINT", "32767")][InlineData("SERIAL2", "SMALLINT", "32767")]
    [InlineData("SERIAL", "INTEGER", "2147483647")][InlineData("SERIAL4", "INTEGER", "2147483647")]
    [InlineData("BIGSERIAL", "BIGINT", "9223372036854775807")][InlineData("SERIAL8", "BIGINT", "9223372036854775807")]
    public async Task ExecuteAsync_SerialAliases_ShouldOwnSharedSequence(string alias, string type, string maximum)
    {
        // Arrange
        await using var engine = SqlDatabaseEngine.Create("serial", new());
        var db = await engine.CreateDatabaseAsync("db", CancellationToken.None);
        await using var session = await db.CreateSessionAsync(CancellationToken.None);
        await Exec(session, "CREATE TABLE t(id " + alias + ")");
        // Act
        await Exec(session, "INSERT INTO t DEFAULT VALUES");
        // Assert
        (await Rows(session, "SELECT DATA_TYPE,MAXIMUM_VALUE FROM INFORMATION_SCHEMA.SEQUENCES WHERE SEQUENCE_NAME='t_id_seq'"))[0].ShouldBe(new object?[] { type, maximum });
        (await Rows(session, "SELECT currval('t_id_seq'),lastval()"))[0].ShouldBe(new object?[] { 1L, 1L });
        await Refuses(session, "DROP SEQUENCE t_id_seq CASCADE", "CS03080");
        await Exec(session, "ALTER TABLE t RENAME COLUMN id TO renamed");
        await Exec(session, "ALTER TABLE t RENAME TO renamed");
        await Exec(session, "INSERT INTO renamed DEFAULT VALUES");
        (await Rows(session, "SELECT currval('t_id_seq')"))[0][0].ShouldBe(2L);
        await Exec(session, "DROP TABLE renamed");
        (await Rows(session, "SELECT * FROM INFORMATION_SCHEMA.SEQUENCES")).ShouldBeEmpty();
    }

    [Fact(DisplayName = "Cohesion Test [Sql] - Identity: ALTER modes, options, restart and DROP retain values")]
    public async Task ExecuteAsync_AlterIdentity_ShouldPreserveRowsAndChangeGeneration()
    {
        // Arrange
        await using var engine = SqlDatabaseEngine.Create("identity-alter", new());
        var db = await engine.CreateDatabaseAsync("db", CancellationToken.None);
        await using var session = await db.CreateSessionAsync(CancellationToken.None);
        await Exec(session, "CREATE TABLE t(id INT NOT NULL)");
        await Exec(session, "INSERT INTO t VALUES (8)");
        // Act / Assert: PostgreSQL tablecmds.c:8322-8625.
        await Exec(session, "ALTER TABLE t ALTER id ADD GENERATED ALWAYS AS IDENTITY (START 10 INCREMENT 2 CACHE 3)");
        await Exec(session, "INSERT INTO t DEFAULT VALUES");
        await Exec(session, "UPDATE t SET id=DEFAULT WHERE id=8");
        await Exec(session, "ALTER TABLE t ALTER id RESTART WITH 20");
        await Exec(session, "ALTER TABLE t ALTER COLUMN id SET INCREMENT BY 3");
        await Exec(session, "ALTER TABLE t ALTER id SET GENERATED BY DEFAULT");
        await Exec(session, "INSERT INTO t VALUES (99)");
        await Exec(session, "INSERT INTO t DEFAULT VALUES");
        (await Rows(session, "SELECT id FROM t ORDER BY id")).Select(row => row[0]).ShouldBe(new object?[] { 10,12,20,99 });
        await Exec(session, "ALTER TABLE t ALTER id DROP IDENTITY");
        await Exec(session, "ALTER TABLE t ALTER id DROP IDENTITY IF EXISTS");
        await Refuses(session, "ALTER TABLE t ALTER id RESTART", "CS03079");
        (await Rows(session, "SELECT * FROM INFORMATION_SCHEMA.SEQUENCES")).ShouldBeEmpty();
    }

    [Fact(DisplayName = "Cohesion Test [Sql] - Identity ALTER: PostgreSQL admission errors and combined options retain atomicity")]
    public async Task ExecuteAsync_IdentityAdmission_ShouldRejectInvalidOwnershipAndRetainValues()
    {
        // Arrange: PostgreSQL tablecmds.c:8322-8680 and sequence.c:1598-1694.
        await using var engine = SqlDatabaseEngine.Create("identity-admission", new());
        var db = await engine.CreateDatabaseAsync("db", CancellationToken.None);
        await using var session = await db.CreateSessionAsync(CancellationToken.None);
        await Exec(session, "CREATE TABLE t(id INT, k INT NOT NULL DEFAULT 3)");
        // Act / Assert
        await Refuses(session, "ALTER TABLE t ALTER id ADD GENERATED ALWAYS AS IDENTITY", "CS03078");
        await Refuses(session, "ALTER TABLE t ALTER id SET GENERATED ALWAYS", "CS03079");
        await Refuses(session, "ALTER TABLE t ALTER k ADD GENERATED ALWAYS AS IDENTITY", "CS03025");
        await Exec(session, "CREATE TABLE bad_type(id TEXT NOT NULL)");
        await Refuses(session, "ALTER TABLE bad_type ALTER id ADD GENERATED ALWAYS AS IDENTITY", "CS03025");
        await Exec(session, "CREATE DOMAIN identity_domain AS INT");
        await Exec(session, "CREATE TABLE bad_domain(id identity_domain NOT NULL)");
        await Refuses(session, "ALTER TABLE bad_domain ALTER id ADD GENERATED ALWAYS AS IDENTITY", "CS03025");
        await Exec(session, "CREATE TABLE two_ids(id SERIAL,other INT NOT NULL)");
        await Refuses(session, "ALTER TABLE two_ids ALTER other ADD GENERATED ALWAYS AS IDENTITY", "CS03025");
        await Exec(session, "ALTER TABLE t ALTER id SET NOT NULL");
        await Exec(session, "ALTER TABLE t ALTER id ADD GENERATED ALWAYS AS IDENTITY");
        await Refuses(session, "ALTER SEQUENCE t_id_seq OWNED BY NONE", "CS03081");
        await Refuses(session, "CREATE SEQUENCE missing_owner OWNED BY missing.id", "CS03081");
        await Exec(session, "CREATE SEQUENCE IF NOT EXISTS t_id_seq OWNED BY missing.id");
        await Exec(session, "ALTER SEQUENCE IF EXISTS missing_seq OWNED BY missing.id");
        await Exec(session, "CREATE SCHEMA other");
        await Refuses(session, "CREATE SEQUENCE other.s OWNED BY dbo.t.k", "CS03081");
        await Exec(session, "ALTER TABLE t ALTER id SET GENERATED BY DEFAULT SET INCREMENT BY 2 SET MAXVALUE 42 RESTART WITH 40");
        await Exec(session, "INSERT INTO t DEFAULT VALUES");
        await Exec(session, "ALTER TABLE t ALTER id SET CACHE 2 SET GENERATED ALWAYS");
        await Exec(session, "INSERT INTO t DEFAULT VALUES");
        await Refuses(session, "INSERT INTO t DEFAULT VALUES", "CS03025");
        (await Rows(session, "SELECT id FROM t ORDER BY id")).Select(row => row[0]).ShouldBe(new object?[] {40,42});
    }

    [Fact(DisplayName = "Cohesion Test [Sql] - Overriding: VALUES, SELECT, conflict and MERGE use one policy")]
    public async Task ExecuteAsync_Overriding_ShouldCoverEveryInsertPath()
    {
        // Arrange
        await using var engine = SqlDatabaseEngine.Create("overriding", new());
        var db = await engine.CreateDatabaseAsync("db", CancellationToken.None);
        await using var session = await db.CreateSessionAsync(CancellationToken.None);
        await Exec(session, "CREATE TABLE t(id INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, k INT UNIQUE)");
        // Act: PostgreSQL rewriteHandler.c:930-972,1015-1027.
        await Exec(session, "INSERT INTO t OVERRIDING SYSTEM VALUE VALUES (20,1)");
        await Exec(session, "INSERT INTO t OVERRIDING USER VALUE VALUES (99,2)");
        await Exec(session, "INSERT INTO t OVERRIDING USER VALUE SELECT DATE '2026-01-01',3");
        await Exec(session, "INSERT INTO t OVERRIDING USER VALUE VALUES (101,2) ON CONFLICT(k) DO UPDATE SET id=DEFAULT");
        await Exec(session, "INSERT INTO t OVERRIDING SYSTEM VALUE VALUES (30,6)");
        await Exec(session, "INSERT INTO t OVERRIDING USER VALUE SELECT 101,3 UNION ALL SELECT 102,6 ON CONFLICT(k) DO UPDATE SET id=DEFAULT");
        await Exec(session, "MERGE INTO t USING (SELECT 5 AS k) s ON t.k=s.k WHEN NOT MATCHED THEN INSERT(id,k) OVERRIDING USER VALUE VALUES(999,s.k)");
        // Assert
        (await Rows(session, "SELECT id,k FROM t ORDER BY k")).Select(row => row[0]).ShouldBe(new object?[] {20,4,6,9,8});
        await Refuses(session, "INSERT INTO t VALUES(70,8)", "CS03025");
    }

    [Fact(DisplayName = "Cohesion Test [Sql] - Identity backfill: populated rows are rewritten before one publication")]
    public async Task ExecuteAsync_PopulatedAddition_ShouldBackfillAndContinue()
    {
        // Arrange
        await using var engine = SqlDatabaseEngine.Create("identity-backfill", new());
        var db = await engine.CreateDatabaseAsync("db", CancellationToken.None);
        await using var session = await db.CreateSessionAsync(CancellationToken.None);
        await Exec(session, "CREATE TABLE t(k INT, tail INT)");
        await Exec(session, "INSERT INTO t(k) VALUES(1),(2),(3)");
        // Act
        await Exec(session, "ALTER TABLE t ADD id BIGINT GENERATED BY DEFAULT AS IDENTITY(START 10 INCREMENT 2)");
        await Exec(session, "INSERT INTO t(k) VALUES(4)");
        // Assert
        (await Rows(session, "SELECT id FROM t ORDER BY k")).Select(row => row[0]).ShouldBe(new object?[] {10L,12L,14L,16L});
        await Exec(session, "TRUNCATE t CONTINUE IDENTITY");
        await Exec(session, "INSERT INTO t(k) VALUES(5)");
        (await Rows(session, "SELECT id FROM t"))[0][0].ShouldBe(18L);
        await Exec(session, "TRUNCATE t RESTART IDENTITY");
        await Exec(session, "INSERT INTO t(k) VALUES(6)");
        (await Rows(session, "SELECT id FROM t"))[0][0].ShouldBe(10L);
    }

    [Fact(DisplayName = "Cohesion Test [Sql] - OWNED BY: detach and table deletion follow ownership")]
    public async Task ExecuteAsync_OwnedBy_ShouldDetachAndDropWithColumn()
    {
        // Arrange
        await using var engine = SqlDatabaseEngine.Create("ownership", new());
        var db = await engine.CreateDatabaseAsync("db", CancellationToken.None);
        await using var session = await db.CreateSessionAsync(CancellationToken.None);
        await Exec(session, "CREATE TABLE t(k INT, tail INT)");
        await Exec(session, "CREATE SEQUENCE s OWNED BY t.k");
        // Act / Assert: PostgreSQL sequence.c:1598-1694.
        await Exec(session, "ALTER SEQUENCE s OWNED BY NONE");
        await Exec(session, "DROP TABLE t");
        (await Rows(session, "SELECT nextval('s')"))[0][0].ShouldBe(1L);
        await Exec(session, "CREATE TABLE t(k INT, tail INT)");
        await Exec(session, "ALTER SEQUENCE s OWNED BY dbo.t.k");
        await Exec(session, "ALTER TABLE t DROP COLUMN k");
        (await Rows(session, "SELECT * FROM INFORMATION_SCHEMA.SEQUENCES")).ShouldBeEmpty();
    }

    [Theory(DisplayName = "Cohesion Test [Sql] - Sequence defaults: RESTRICT names the default and CASCADE removes it")]
    [InlineData("nextval('s'::regclass)")][InlineData("NEXT VALUE FOR s")]
    public async Task ExecuteAsync_SequenceDefault_ShouldTrackDependency(string expression)
    {
        // Arrange
        await using var engine = SqlDatabaseEngine.Create("defaults", new());
        var db = await engine.CreateDatabaseAsync("db", CancellationToken.None);
        await using var session = await db.CreateSessionAsync(CancellationToken.None);
        await Exec(session, "CREATE SEQUENCE s START 7");
        await Exec(session, "CREATE TABLE t(k BIGINT DEFAULT " + expression + ")");
        // Act / Assert
        await Exec(session, "INSERT INTO t DEFAULT VALUES");
        (await Rows(session, "SELECT k FROM t"))[0][0].ShouldBe(7L);
        await Refuses(session, "DROP SEQUENCE s RESTRICT", "CS03080");
        await Exec(session, "DROP SEQUENCE s CASCADE");
        await Exec(session, "INSERT INTO t DEFAULT VALUES");
        (await Rows(session, "SELECT k FROM t ORDER BY k NULLS FIRST"))[0][0].ShouldBeNull();
    }

    private static async Task Exec(SqlDatabaseSession session, string sql)
    { var result = await session.ExecuteAsync(sql, cancellationToken: CancellationToken.None); result.Diagnostics.ShouldNotContain(d => d.Severity == Types.DiagnosticSeverity.Error); }
    private static async Task Refuses(SqlDatabaseSession session, string sql, string code)
    { var failure = await Should.ThrowAsync<DatabaseException>(() => Exec(session, sql)); failure.Diagnostics[0].Code.ShouldBe(code); }
    private static async Task<List<object?[]>> Rows(SqlDatabaseSession session, string sql)
    {
        await using var result = (DatabaseResultSet)await session.ExecuteAsync(sql, cancellationToken: CancellationToken.None);
        var rows = new List<object?[]>();
        await foreach (var row in result.GetRowsAsync(CancellationToken.None)) { rows.Add(Enumerable.Range(0,row.FieldCount).Select(row.GetValue).ToArray()); }
        return rows;
    }
