    [Theory(DisplayName = "Cohesion Test [Sql] - Sequence default DDL: deletion during the grant wait cannot publish a dangling dependency")]
    [InlineData(false)][InlineData(true)]
    public async Task ExecuteAsync_DefaultPublicationRace_ShouldRefuseDeletedSequence(bool alter)
    {
        // Arrange
        using var timeout = new CancellationTokenSource(TimeSpan.FromSeconds(60));
        await using var engine = SqlDatabaseEngine.Create("default-publication-race", new());
        var db = await engine.CreateDatabaseAsync("db", timeout.Token);
        await using var creator = await db.CreateSessionAsync(timeout.Token);
        await using var dropper = await db.CreateSessionAsync(timeout.Token);
        await Exec(creator, "CREATE SEQUENCE s");
        if (alter) { await Exec(creator, "CREATE TABLE t(a BIGINT)"); }
        var entered = new TaskCompletionSource(TaskCreationOptions.RunContinuationsAsynchronously);
        var release = new TaskCompletionSource(TaskCreationOptions.RunContinuationsAsynchronously);
        var waited = new TaskCompletionSource(TaskCreationOptions.RunContinuationsAsynchronously);
        using var listener = new LockWaitListener(db.Name);
        listener.Observed = e => { if (e.EventName == "LockWaitStart") { waited.TrySetResult(); } };
        Task? dropping = null, creating = null;
        SqlPlanExecutor.BeforeSequenceMetadataLease = () => { entered.TrySetResult(); release.Task.GetAwaiter().GetResult(); };
        try
        {
            // Act: DROP holds X; binding sees s, then its Shared request waits for deletion.
            dropping = Task.Run(() => Exec(dropper, "DROP SEQUENCE s"));
            await entered.Task.WaitAsync(timeout.Token);
            creating = Task.Run(() => Exec(creator, alter ? "ALTER TABLE t ALTER a SET DEFAULT nextval('s')" : "CREATE TABLE t(a BIGINT DEFAULT nextval('s'))"));
            await waited.Task.WaitAsync(timeout.Token);
            release.TrySetResult();
            await dropping.WaitAsync(timeout.Token);
            var failure = await Should.ThrowAsync<DatabaseException>(() => creating.WaitAsync(timeout.Token));
            // Assert
            failure.Diagnostics[0].Code.ShouldBe("CS03073");
            db.Catalog.TryGetTable("dbo", "t", out var table).ShouldBe(alter);
            if (alter) { table.Columns[0].DefaultLiteral.ShouldBeNull(); }
        }
        finally
        {
            release.TrySetResult(); SqlPlanExecutor.BeforeSequenceMetadataLease = null;
            if (dropping is not null) { await dropping.WaitAsync(timeout.Token); }
            if (creating is not null) { try { await creating.WaitAsync(timeout.Token); } catch (DatabaseException) { } }
        }
    }

    [Theory(DisplayName = "Cohesion Test [Sql] - Identity backfill: every durable boundary recovers old or complete columns")]
    [InlineData(StorageCommitDurability.Synchronous)][InlineData(StorageCommitDurability.Grouped)][InlineData(StorageCommitDurability.None)]
    public async Task Reopen_BackfillCrashImages_ShouldRecoverCompleteDefinition(StorageCommitDurability durability)
    {
        // Arrange
        using var timeout = new CancellationTokenSource(TimeSpan.FromMinutes(4));
        var strategy = new CrashCaptureSqlStorageStrategy(durability);
        CrashCaptureSqlStorageStrategy.CrashPointRecorder recorder;
        int stages = 0;
        await using (var engine = SqlDatabaseEngine.Create("backfill-crash", new() { StorageStrategy = strategy, Durability = durability }))
        {
            var db = await engine.CreateDatabaseAsync("db", timeout.Token);
            await using var session = await db.CreateSessionAsync(timeout.Token);
            await Exec(session, "CREATE TABLE t(k INT)");
            await Exec(session, "INSERT INTO t VALUES(1),(2),(3)");
            SqlPlanExecutor.RewriteStage = (_, _) => stages++;
            try
            {
                // Act
                using (recorder = strategy.RecordCrashPoints())
                { await Exec(session, "ALTER TABLE t ADD id BIGINT GENERATED BY DEFAULT AS IDENTITY(START 10 INCREMENT 2)"); }
            }
            finally { SqlPlanExecutor.RewriteStage = null; }
            (await Rows(session, "SELECT currval('t_id_seq'),lastval()"))[0].ShouldBe(new object?[] {14L,14L});
        }
        // Assert
        stages.ShouldBe(4);
        int old = 0, complete = 0;
        for (int point = 0; point < recorder.Count; point++)
        {
            await using var recovered = SqlDatabaseEngine.Create("backfill-recover", new() { StorageStrategy = recorder.Open(point), Durability = durability });
            var db = await recovered.OpenDatabaseAsync("db", timeout.Token);
            await using var session = await db.CreateSessionAsync(timeout.Token);
            db.Catalog.TryGetTable("dbo", "t", out var table).ShouldBeTrue();
            (await Rows(session, "SELECT k FROM t ORDER BY k")).Select(row => row[0]).ShouldBe(new object?[] {1,2,3});
            if (table.Columns.Count == 1)
            { old++; (await Rows(session, "SELECT * FROM INFORMATION_SCHEMA.SEQUENCES")).ShouldBeEmpty(); }
            else
            {
                complete++;
                (await Rows(session, "SELECT id FROM t ORDER BY k")).Select(row => row[0]).ShouldBe(new object?[] {10L,12L,14L});
                await Exec(session, "INSERT INTO t(k) VALUES(4)");
                Convert.ToInt64((await Rows(session, "SELECT id FROM t WHERE k=4"))[0][0]).ShouldBeGreaterThan(14);
            }
        }
        old.ShouldBeGreaterThan(0); complete.ShouldBeGreaterThan(0);
    }

    [Theory(DisplayName = "Cohesion Test [Sql] - Identity ALTER: insertion grants force a real wait and release on cancellation")]
    [InlineData("RESTART WITH 10")][InlineData("SET INCREMENT BY 2")][InlineData("SET GENERATED ALWAYS")][InlineData("DROP IDENTITY")][InlineData("TRUNCATE")]
    public async Task ExecuteAsync_IdentityDdlStress_ShouldExerciseWaitAndRelease(string action)
    {
        // Arrange
        using var timeout = new CancellationTokenSource(TimeSpan.FromSeconds(60));
        await using var engine = SqlDatabaseEngine.Create("identity-stress", new());
        var db = await engine.CreateDatabaseAsync("db", timeout.Token);
        await using var writer = await db.CreateSessionAsync(timeout.Token);
        await using var ddl = await db.CreateSessionAsync(timeout.Token);
        await Exec(writer, "CREATE TABLE t(id SERIAL, k INT)");
        string sql = action == "TRUNCATE" ? "TRUNCATE t RESTART IDENTITY" : "ALTER TABLE t ALTER id " + action;
        int waits = 0, inserts = 0, alterations = 0, cancellations = 0;
        var elapsed = Stopwatch.StartNew();
        // Act: each round proves a sequence S/X conflict before ending the writer.
        do
        {
            await using var transaction = await writer.BeginTransactionAsync(timeout.Token);
            await Exec(writer, "INSERT INTO t(k) VALUES(1)"); inserts++;
            var observed = new TaskCompletionSource(TaskCreationOptions.RunContinuationsAsynchronously);
            using var listener = new LockWaitListener(db.Name);
            listener.Observed = e => { if (e.EventName == "LockWaitStart") { Interlocked.Increment(ref waits); observed.TrySetResult(); } };
            using var cancel = CancellationTokenSource.CreateLinkedTokenSource(timeout.Token);
            var pending = ddl.ExecuteAsync(sql, cancellationToken: cancel.Token).AsTask();
            await observed.Task.WaitAsync(timeout.Token);
            if (cancellations == 0)
            { cancel.Cancel(); await Should.ThrowAsync<OperationCanceledException>(async () => await pending); cancellations++; }
            await transaction.CommitAsync(timeout.Token);
            if (cancel.IsCancellationRequested) { await Exec(ddl, sql); } else { await pending; }
            alterations++;
            if (action == "DROP IDENTITY") { await Exec(ddl, "ALTER TABLE t ALTER id ADD GENERATED BY DEFAULT AS IDENTITY"); }
        } while (elapsed.Elapsed < TimeSpan.FromSeconds(1) || waits < 2 || alterations < 2);
        // Assert
        waits.ShouldBeGreaterThanOrEqualTo(2); inserts.ShouldBe(alterations); cancellations.ShouldBe(1);
        await Exec(writer, "INSERT INTO t(k) VALUES(2)");
    }

    [Fact(DisplayName = "Cohesion Test [Sql] - Multi-table TRUNCATE: differing identity columns restart together")]
    public async Task ExecuteAsync_MultipleOwnedTables_ShouldRestartEverySequence()
    {
        // Arrange
        await using var engine = SqlDatabaseEngine.Create("multi-identities", new());
        var db = await engine.CreateDatabaseAsync("db", CancellationToken.None);
        await using var session = await db.CreateSessionAsync(CancellationToken.None);
        await Exec(session, "CREATE TABLE a(id SERIAL)");
        await Exec(session, "CREATE TABLE b(other_id BIGSERIAL)");
        await Exec(session, "INSERT INTO a DEFAULT VALUES");
        await Exec(session, "INSERT INTO b DEFAULT VALUES");
        // Act
        await Exec(session, "TRUNCATE a,b RESTART IDENTITY");
        await Exec(session, "INSERT INTO a DEFAULT VALUES");
        await Exec(session, "INSERT INTO b DEFAULT VALUES");
        // Assert
        (await Rows(session, "SELECT currval('a_id_seq'),currval('b_other_id_seq')"))[0].ShouldBe(new object?[] {1L,1L});
    }

    [Fact(DisplayName = "Cohesion Test [Sql] - Sequence defaults and references: implicit allocation shares row scope and validates dependencies")]
    public async Task ExecuteAsync_DefaultClosure_ShouldAllocateAndValidateBeforePublication()
    {
        // Arrange
        await using var engine = SqlDatabaseEngine.Create("default-closure", new());
        var db = await engine.CreateDatabaseAsync("db", CancellationToken.None);
        await using var session = await db.CreateSessionAsync(CancellationToken.None);
        await Exec(session, "CREATE SEQUENCE s");
        await Exec(session, "CREATE TABLE t(a BIGINT DEFAULT NEXT VALUE FOR s,b BIGINT DEFAULT NEXT VALUE FOR s)");
        // Act / Assert
        await Exec(session, "INSERT INTO t(a) VALUES(NEXT VALUE FOR s),(DEFAULT)");
        (await Rows(session, "SELECT a,b FROM t ORDER BY a"))[0].ShouldBe(new object?[] {1L,1L});
        (await Rows(session, "SELECT a,b FROM t ORDER BY a"))[1].ShouldBe(new object?[] {2L,2L});
        await Refuses(session, "CREATE TABLE bad(d DATE DEFAULT nextval('s'))", "CS05013");
        await Exec(session, @"CREATE SEQUENCE ""true""");
        await Refuses(session, "CREATE TABLE bad_argument(d BIGINT DEFAULT nextval(TRUE))", "CS03077");
        await Exec(session, "CREATE TABLE rp(id BIGINT PRIMARY KEY)");
        await Exec(session, "INSERT INTO rp VALUES(1),(2),(10),(11)");
        await Exec(session, "CREATE SEQUENCE rs START 10");
        await Exec(session, "CREATE TABLE rc(k INT,pid BIGINT DEFAULT NEXT VALUE FOR rs REFERENCES rp(id) ON DELETE SET DEFAULT)");
        await Exec(session, "INSERT INTO rc VALUES(1,1),(2,2)");
        await Exec(session, "DELETE FROM rp WHERE id IN(1,2)");
        (await Rows(session, "SELECT pid FROM rc ORDER BY pid")).Select(row => row[0]).ShouldBe(new object?[] {10L,11L});
        await Exec(session, "CREATE TABLE p(id INT PRIMARY KEY)");
        await Exec(session, "INSERT INTO p VALUES(1),(2)");
        await Exec(session, "CREATE TABLE child(id INT GENERATED ALWAYS AS IDENTITY(START 2) REFERENCES p(id) ON DELETE SET DEFAULT)");
        await Exec(session, "INSERT INTO child OVERRIDING SYSTEM VALUE VALUES(1)");
        await Exec(session, "DELETE FROM p WHERE id=1");
        (await Rows(session, "SELECT currval('child_id_seq'),lastval()"))[0].ShouldBe(new object?[] {2L,2L});
        await Exec(session, "CREATE TABLE backfill(k INT)");
        await Exec(session, "INSERT INTO backfill VALUES(1),(2),(3)");
        await Should.ThrowAsync<DatabaseException>(() => Exec(session, "ALTER TABLE backfill ADD id SERIAL REFERENCES p(id)"));
        db.Catalog.TryGetTable("dbo", "backfill", out var table).ShouldBeTrue(); table.Columns.Count.ShouldBe(1);
    }
