    [Fact(DisplayName = "Cohesion Test [SqlEngine] - Upsert: identities are consumed by skipped and updated proposals")]
    public async Task ExecuteAsync_IdentityConflicts_ShouldConsumeAllocatedValues()
    {
        // Arrange
        await using var engine = SqlDatabaseEngine.Create("upsert", new());
        var database = await engine.CreateDatabaseAsync("app");
        await using var session = await database.CreateSessionAsync();
        await session.ExecuteAsync("CREATE TABLE t (id INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, name TEXT UNIQUE, age INT)");
        await session.ExecuteAsync("INSERT INTO t (name, age) VALUES ('a', 10)");

        // Act
        (await session.ExecuteAsync("INSERT INTO t (name, age) VALUES ('a', 20) ON CONFLICT DO NOTHING")).AffectedCount.ShouldBe(0);
        (await session.ExecuteAsync("INSERT INTO t (name, age) VALUES ('a', 30) ON CONFLICT (name) DO UPDATE SET age = EXCLUDED.id")).AffectedCount.ShouldBe(1);
        await session.ExecuteAsync("INSERT INTO t (name, age) VALUES ('b', 40)");

        // Assert
        CheckRows(await RowsAsync(session, "SELECT * FROM t ORDER BY id"), [[1, "a", 3], [4, "b", 40]]);
        var failure = await Should.ThrowAsync<DatabaseException>(async () => await session.ExecuteAsync(
            "INSERT INTO t (name) VALUES ('a') ON CONFLICT (name) DO UPDATE SET id = DEFAULT"));
        failure.Diagnostics.ShouldContain(diagnostic => diagnostic.Code == "COHSQLE025");
    }

    [Fact(DisplayName = "Cohesion Test [SqlEngine] - Upsert: materialized SELECT and DEFAULT VALUES share arbitration")]
    public async Task ExecuteAsync_SelectAndDefault_ShouldUseSharedWritePath()
    {
        // Arrange
        await using var engine = SqlDatabaseEngine.Create("upsert", new());
        var database = await engine.CreateDatabaseAsync("app");
        await using var session = await database.CreateSessionAsync();
        await session.ExecuteAsync("CREATE TABLE t (id INT PRIMARY KEY DEFAULT 1, age INT DEFAULT 5)");
        await session.ExecuteAsync("INSERT INTO t VALUES (1, 10), (2, 20)");

        // Act / Assert
        (await session.ExecuteAsync("INSERT INTO t SELECT id, age + 1 FROM t ON CONFLICT (id) DO UPDATE SET age = EXCLUDED.age")).AffectedCount.ShouldBe(2);
        (await session.ExecuteAsync("INSERT INTO t DEFAULT VALUES ON CONFLICT (id) DO UPDATE SET age = DEFAULT")).AffectedCount.ShouldBe(1);
        CheckRows(await RowsAsync(session, "SELECT * FROM t ORDER BY id"), [[1, 5], [2, 21]]);
    }

    private static async Task<List<object?[]>> RowsAsync(SqlDatabaseSession session, string sql)
    {
        await using var result = (DatabaseResultSet)await session.ExecuteAsync(sql, cancellationToken: CancellationToken.None);
        return await ReadAsync(result);
    }

    private static async Task<List<object?[]>> ReadAsync(DatabaseResultSet result)
    {
        var rows = new List<object?[]>();
        await foreach (var row in result.GetRowsAsync(CancellationToken.None))
        { rows.Add(Enumerable.Range(0, row.FieldCount).Select(row.GetValue).ToArray()); }
        return rows;
    }

    private static void CheckRows(IReadOnlyList<object?[]> actual, object?[][] expected)
    {
        actual.Count.ShouldBe(expected.Length);
        for (int index = 0; index < actual.Count; index++) { actual[index].ShouldBe(expected[index]); }
    }
