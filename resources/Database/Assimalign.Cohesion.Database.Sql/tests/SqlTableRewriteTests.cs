    [Fact(DisplayName = "Cohesion Test [Sql] - Rewrite: dense rows, missing tails, indexes, views and old snapshots converge together")]
    public async Task RewriteTableAsync_PinnedLayout_ShouldCompactAndPreserveBothImages()
    {
        // Arrange
        using var timeout = new CancellationTokenSource(TimeSpan.FromSeconds(30));
        await using var engine = SqlDatabaseEngine.Create("rewrite", new());
        var database = await engine.CreateDatabaseAsync("db", timeout.Token);
        await using var session = await database.CreateSessionAsync(timeout.Token);
        await using var reader = await database.CreateSessionAsync(timeout.Token);
        await ExecAsync(session, "CREATE TABLE t (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, gone INT, value INT CHECK(value > 0))", timeout.Token);
        await ExecAsync(session, "INSERT INTO t(gone,value) VALUES (99,10),(98,20)", timeout.Token);
        await ExecAsync(session, "ALTER TABLE t DROP COLUMN gone", timeout.Token);
        await ExecAsync(session, "ALTER TABLE t ADD COLUMN tail INT DEFAULT 7", timeout.Token);
        await ExecAsync(session, "ALTER TABLE t ALTER COLUMN tail SET DEFAULT 9", timeout.Token);
        await ExecAsync(session, "CREATE UNIQUE INDEX ix ON t(value)", timeout.Token);
        await ExecAsync(session, "CREATE TABLE child (id BIGINT REFERENCES t(id))", timeout.Token);
        await ExecAsync(session, "INSERT INTO child VALUES (1)", timeout.Token);
        await ExecAsync(session, "CREATE VIEW v AS SELECT id,value,tail FROM t", timeout.Token);
        var previous = Table(database);
        ulong generation = database.Catalog.DdlGeneration;
        var pages = database.DataStorage.GetOwnerPages(previous.ObjectId).ToArray();
        await using var snapshot = await reader.BeginTransactionAsync(timeout.Token);
        await ExecAsync(session, "UPDATE t SET value=11 WHERE id=1", timeout.Token);
        await ExecAsync(session, "DELETE FROM t WHERE id=2", timeout.Token);

        // Act
        await database.RewriteTableAsync(previous, timeout.Token);

        // Assert
        var current = Table(database);
        current.ObjectId.ShouldNotBe(previous.ObjectId);
        current.DroppedColumnOrdinals.ShouldBeEmpty();
        current.PhysicalColumnCount.ShouldBe(3);
        Enumerable.Range(0, 3).Select(current.GetPhysicalOrdinal).ShouldBe(new[] { 0, 1, 2 });
        database.Catalog.DdlGeneration.ShouldBe(generation);
        database.Catalog.GetIndexes(current.ObjectId).Count.ShouldBe(2);
        (await RowsAsync(session, "SELECT * FROM v WHERE value=11", timeout.Token)).ShouldHaveSingleItem().ShouldBe(new object?[] { 1L, 11, 7 });
        (await RowsAsync(reader, "SELECT * FROM v WHERE value=10", timeout.Token)).ShouldHaveSingleItem().ShouldBe(new object?[] { 1L, 10, 7 });
        (await RowsAsync(reader, "SELECT id FROM t ORDER BY id", timeout.Token)).Select(row => row[0]).ShouldBe(new object?[] { 1L, 2L });
        await Should.ThrowAsync<DatabaseException>(() => ExecAsync(session, "INSERT INTO t(value) VALUES (11)", timeout.Token));
        await Should.ThrowAsync<DatabaseException>(() => ExecAsync(session, "INSERT INTO t(value) VALUES (-1)", timeout.Token));
        await Should.ThrowAsync<DatabaseException>(() => ExecAsync(session, "DELETE FROM t WHERE id=1", timeout.Token));
        await ExecAsync(session, "INSERT INTO t(value) VALUES (30)", timeout.Token);
        (await RowsAsync(session, "SELECT tail FROM t WHERE value=30", timeout.Token)).ShouldHaveSingleItem()[0].ShouldBe(9);
        database.TableReclamation.RunBatch(timeout.Token);
        database.DataStorage.GetOwnerPages(previous.ObjectId).ShouldBe(pages);
        await snapshot.RollbackAsync(timeout.Token);
        await ReclaimAsync(database, timeout.Token);
        database.DataStorage.GetOwnerPages(previous.ObjectId).ShouldBeEmpty();
        await ExecAsync(session, "ALTER TABLE t ADD COLUMN again INT", timeout.Token);
        Table(database).GetPhysicalOrdinal(3).ShouldBe(3);
    }

