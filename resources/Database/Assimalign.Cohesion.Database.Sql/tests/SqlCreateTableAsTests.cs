    [Fact(DisplayName = "Cohesion Test [Sql] - CTAS: view output metadata, bags and renaming are retained without keys/defaults/identity")]
    public async Task ExecuteAsync_InferredOutput_ShouldRetainMetadataAndRows()
    {
        // Arrange
        using var timeout = new CancellationTokenSource(TimeSpan.FromSeconds(60));
        await using var engine = SqlDatabaseEngine.Create("ctas-types", new());
        var database = await engine.CreateDatabaseAsync("db", timeout.Token);
        await using var session = await database.CreateSessionAsync(timeout.Token);
        await ExecAsync(session, "CREATE TABLE src (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, amount DECIMAL(12,3) NOT NULL, label VARCHAR(19) COLLATE case_insensitive, fixed CHAR(4), stamp TIMESTAMP WITH TIME ZONE, bytes BINARY)", timeout.Token);
        await ExecAsync(session, "INSERT INTO src(amount,label,fixed,stamp,bytes) VALUES (1.125,'Ab','xy',TIMESTAMP WITH TIME ZONE '2026-01-02 03:04:05+00:00',X'0102'),(2.5,NULL,NULL,NULL,NULL)", timeout.Token);
        await ExecAsync(session, "CREATE VIEW expected AS SELECT * FROM src", timeout.Token);

        // Act
        await ExecAsync(session, "CREATE TABLE copy AS SELECT * FROM src", timeout.Token);
        await ExecAsync(session, "CREATE TABLE renamed (n,word) AS WITH q AS (SELECT id,label FROM src) SELECT id,label FROM q UNION ALL SELECT id,label FROM src", timeout.Token);

        // Assert
        var copy = database.Catalog.Tables.Single(t => t.Name == "copy");
        var expected = database.Catalog.Views.Single(v => v.Name == "expected");
        for (int i = 0; i < copy.Columns.Count; i++)
        {
            var column = copy.Columns[i];
            column.Name.ShouldBe(expected.Columns[i].Name);
            column.Type.ShouldBe(expected.Columns[i].Type);
            column.IsNullable.ShouldBe(expected.Columns[i].IsNullable);
            column.Collation.ShouldBe(expected.Columns[i].Collation);
            column.DefaultLiteral.ShouldBeNull();
            column.Identity.ShouldBeNull();
        }
        copy.PrimaryKeyColumns.ShouldBeEmpty();
        copy.Constraints.ShouldBeEmpty();
        database.Catalog.GetIndexes(copy.ObjectId).ShouldBeEmpty();
        var rows = await RowsAsync(session, "SELECT * FROM copy ORDER BY id", timeout.Token);
        rows.Count.ShouldBe(2);
        rows[0][1].ShouldBe(1.125m);
        rows[0][3].ShouldBe("xy  ");
        ((byte[])rows[0][5]!).ShouldBe(new byte[] { 1, 2 });
        (await RowsAsync(session, "SELECT n FROM renamed ORDER BY n", timeout.Token)).Select(r => r[0]).ShouldBe(new object?[] { 1L, 1L, 2L, 2L });
        await ExecAsync(session, "INSERT INTO copy VALUES (1,3,'ab',NULL,NULL,NULL)", timeout.Token);
    }

    [Theory(DisplayName = "Cohesion Test [Sql] - CTAS: WITH NO DATA binds types without evaluating rows or counts")]
    [InlineData("SELECT CAST('bad' AS INT) AS n")]
    [InlineData("SELECT 1/0 AS n")]
    [InlineData("SELECT id AS n FROM src WHERE id=1/0 LIMIT 1/0")]
    [InlineData("WITH q AS (SELECT CAST('bad' AS INT) AS n) SELECT n FROM q")]
    public async Task ExecuteAsync_NoData_ShouldSkipEvaluation(string query)
    {
        // Arrange
        using var timeout = new CancellationTokenSource(TimeSpan.FromSeconds(30));
        await using var engine = SqlDatabaseEngine.Create("ctas-no-data", new());
        var database = await engine.CreateDatabaseAsync("db", timeout.Token);
        await using var session = await database.CreateSessionAsync(timeout.Token);
        await ExecAsync(session, "CREATE TABLE src (id INT)", timeout.Token);
        await ExecAsync(session, "INSERT INTO src VALUES(1)", timeout.Token);

        // Act
        await ExecAsync(session, "CREATE TABLE empty AS " + query + " WITH NO DATA", timeout.Token);

        // Assert
        database.Catalog.Tables.Single(t => t.Name == "empty").Columns.ShouldHaveSingleItem().Type.Type
            .ShouldBe(query == "SELECT 1/0 AS n" ? DatabaseType.Int64 : DatabaseType.Int32);
        (await RowsAsync(session, "SELECT * FROM empty", timeout.Token)).ShouldBeEmpty();
        await ExecAsync(session, "CREATE TABLE IF NOT EXISTS empty AS SELECT missing FROM absent", timeout.Token);
        (await RowsAsync(session, "SELECT * FROM empty", timeout.Token)).ShouldBeEmpty();
    }

    [Theory(DisplayName = "Cohesion Test [Sql] - CTAS: names must be complete, distinct and explicit for unnamed expressions")]
    [InlineData("CREATE TABLE bad AS SELECT 1")]
    [InlineData("CREATE TABLE bad AS SELECT 1 AS n,2 AS n")]
    [InlineData("CREATE TABLE bad (n,N) AS SELECT 1,2")]
    [InlineData("CREATE TABLE bad (n) AS SELECT 1,2")]
    [InlineData("CREATE TABLE bad (\" \" ) AS SELECT 1")]
    [InlineData("CREATE TABLE bad AS SELECT 1 UNION ALL SELECT 2")]
    public async Task ExecuteAsync_InvalidNames_ShouldFailBeforeReservation(string sql)
    {
        // Arrange
        using var timeout = new CancellationTokenSource(TimeSpan.FromSeconds(30));
        await using var engine = SqlDatabaseEngine.Create("ctas-names", new());
        var database = await engine.CreateDatabaseAsync("db", timeout.Token);
        await using var session = await database.CreateSessionAsync(timeout.Token);

        // Act
        var failure = await Should.ThrowAsync<DatabaseException>(() => ExecAsync(session, sql, timeout.Token));

        // Assert
        failure.Diagnostics.ShouldHaveSingleItem().Code.ShouldBe("CS03068");
        database.Catalog.Tables.ShouldBeEmpty();
        database.Catalog.GetPendingTableReclamations().ShouldBeEmpty();
        await ExecAsync(session, "CREATE TABLE bad (n) AS SELECT 1", timeout.Token);
        (await RowsAsync(session, "SELECT * FROM bad", timeout.Token)).ShouldHaveSingleItem()[0].ShouldBe(1);
    }

    [Theory(DisplayName = "Cohesion Test [Sql] - CTAS: conversion and domain failures leave no table and permit retry")]
    [InlineData("SELECT CAST('bad' AS INT) AS n FROM src")]
    [InlineData("SELECT CAST(-1 AS positive) AS n FROM src")]
    public async Task ExecuteAsync_DataFailure_ShouldLeaveNoTable(string query)
    {
        // Arrange
        using var timeout = new CancellationTokenSource(TimeSpan.FromSeconds(30));
        await using var engine = SqlDatabaseEngine.Create("ctas-values", new());
        var database = await engine.CreateDatabaseAsync("db", timeout.Token);
        await using var session = await database.CreateSessionAsync(timeout.Token);
        await ExecAsync(session, "CREATE DOMAIN positive AS INT CHECK(VALUE > 0)", timeout.Token);
        await ExecAsync(session, "CREATE TABLE src (id INT)", timeout.Token);
        await ExecAsync(session, "INSERT INTO src VALUES(1)", timeout.Token);

        // Act
        await Should.ThrowAsync<DatabaseException>(() => ExecAsync(session, "CREATE TABLE bad AS " + query, timeout.Token));

        // Assert
        database.Catalog.TryGetTable("dbo", "bad", out _).ShouldBeFalse();
        database.Coordinator.GetOpenContexts().ShouldBeEmpty();
        await ReclaimAsync(database, timeout.Token);
        database.Catalog.GetPendingTableReclamations().ShouldBeEmpty();
        await ExecAsync(session, "CREATE TABLE bad AS SELECT id FROM src", timeout.Token);
    }

    [Theory(DisplayName = "Cohesion Test [Sql] - CTAS: every interrupted build abandons only its unpublished owner and releases admission")]
    [InlineData("Reserved", false)]
    [InlineData("Copied", false)]
    [InlineData("Prepared", false)]
    [InlineData("BuilderCommitted", false)]
    [InlineData("Reserved", true)]
    [InlineData("Copied", true)]
    [InlineData("Prepared", true)]
    [InlineData("BuilderCommitted", true)]
    public async Task ExecuteAsync_InterruptedBuild_ShouldReclaimAndAllowRetry(string stage, bool cancel)
    {
        // Arrange
        using var timeout = new CancellationTokenSource(TimeSpan.FromSeconds(60));
        using var cancellation = CancellationTokenSource.CreateLinkedTokenSource(timeout.Token);
        await using var engine = SqlDatabaseEngine.Create("ctas-interrupt", new());
        var database = await engine.CreateDatabaseAsync("db", timeout.Token);
        await using var session = await database.CreateSessionAsync(timeout.Token);
        await SeedAsync(session, timeout.Token);
        ulong owner = 0;
        int observed = 0;
        SqlPlanExecutor.TableAsStage = (point, id) =>
        {
            owner = id;
            if (point != stage) { return; }
            observed++;
            if (cancel) { cancellation.Cancel(); }
            else { throw new InvalidOperationException("Injected CTAS interruption"); }
        };
        try
        {
            // Act
            if (cancel) { await Should.ThrowAsync<OperationCanceledException>(() => ExecAsync(session, "CREATE TABLE copy AS SELECT id FROM src", cancellation.Token)); }
            else { await Should.ThrowAsync<InvalidOperationException>(() => ExecAsync(session, "CREATE TABLE copy AS SELECT id FROM src", timeout.Token)); }
        }
        finally { SqlPlanExecutor.TableAsStage = null; }

        // Assert
        observed.ShouldBe(1);
        owner.ShouldBeGreaterThan(0UL);
        session.LastStatementMetrics.ShouldNotBeNull().HashMemoryBytes.ShouldBe(0);
        database.Catalog.TryGetTable("dbo", "copy", out _).ShouldBeFalse();
        database.Coordinator.GetOpenContexts().ShouldBeEmpty();
        await ReclaimAsync(database, timeout.Token);
        database.DataStorage.HasOwnerPages(owner).ShouldBeFalse();
        await ExecAsync(session, "CREATE TABLE copy AS SELECT id FROM src", timeout.Token);
        (await RowsAsync(session, "SELECT * FROM copy", timeout.Token)).Count.ShouldBe(65);
    }

    [Fact(DisplayName = "Cohesion Test [Sql] - CTAS: explicit transaction refusal retains earlier writes")]
    public async Task ExecuteAsync_ExplicitTransaction_ShouldRefuseAndRemainActive()
    {
        // Arrange
        using var timeout = new CancellationTokenSource(TimeSpan.FromSeconds(30));
        await using var engine = SqlDatabaseEngine.Create("ctas-transaction", new());
        var database = await engine.CreateDatabaseAsync("db", timeout.Token);
        await using var session = await database.CreateSessionAsync(timeout.Token);
        await ExecAsync(session, "CREATE TABLE src (id INT)", timeout.Token);
        await using var transaction = await session.BeginTransactionAsync(timeout.Token);
        await ExecAsync(session, "INSERT INTO src VALUES(1)", timeout.Token);

        // Act
        var result = await session.ExecuteAsync("CREATE TABLE copy AS SELECT id FROM src", cancellationToken: timeout.Token);

        // Assert
        result.Status.ShouldBe(DatabaseResultStatus.Error);
        result.Diagnostics.ShouldHaveSingleItem().Code.ShouldBe("CS04003");
        await transaction.CommitAsync(timeout.Token);
        (await RowsAsync(session, "SELECT * FROM src", timeout.Token)).ShouldHaveSingleItem()[0].ShouldBe(1);
        database.Catalog.TryGetTable("dbo", "copy", out _).ShouldBeFalse();
    }

    [Fact(DisplayName = "Cohesion Test [Sql] - CTAS: NULL outputs become nullable text and explicit names can replace synthesized labels")]
    public async Task ExecuteAsync_UnknownOutput_ShouldCreateUsableNullableText()
    {
        // Arrange
        using var timeout = new CancellationTokenSource(TimeSpan.FromSeconds(30));
        await using var engine = SqlDatabaseEngine.Create("ctas-null", new());
        var database = await engine.CreateDatabaseAsync("db", timeout.Token);
        await using var session = await database.CreateSessionAsync(timeout.Token);

        // Act
        await ExecAsync(session, "CREATE TABLE copy (value) AS SELECT NULL WITH DATA", timeout.Token);

        // Assert
        var column = database.Catalog.Tables.ShouldHaveSingleItem().Columns.ShouldHaveSingleItem();
        column.Type.Type.ShouldBe(DatabaseType.String);
        column.IsNullable.ShouldBeTrue();
        (await RowsAsync(session, "SELECT * FROM copy", timeout.Token)).ShouldHaveSingleItem()[0].ShouldBeNull();
        await ExecAsync(session, "INSERT INTO copy VALUES('later')", timeout.Token);
        (await RowsAsync(session, "SELECT value FROM copy WHERE value IS NOT NULL", timeout.Token)).ShouldHaveSingleItem()[0].ShouldBe("later");
    }

    [Fact(DisplayName = "Cohesion Test [Sql] - CTAS: cancellation after publication returns the complete committed table")]
    public async Task ExecuteAsync_CanceledAfterPublication_ShouldReturnCommittedResult()
    {
        // Arrange
        using var timeout = new CancellationTokenSource(TimeSpan.FromSeconds(30));
        using var cancellation = CancellationTokenSource.CreateLinkedTokenSource(timeout.Token);
        await using var engine = SqlDatabaseEngine.Create("ctas-committed", new());
        var database = await engine.CreateDatabaseAsync("db", timeout.Token);
        await using var session = await database.CreateSessionAsync(timeout.Token);
        await SeedAsync(session, timeout.Token);
        int published = 0;
        SqlPlanExecutor.AfterSelfCommit = () => { published++; cancellation.Cancel(); };
        try
        {
            // Act
            await ExecAsync(session, "CREATE TABLE copy AS SELECT * FROM src", cancellation.Token);
        }
        finally { SqlPlanExecutor.AfterSelfCommit = null; }

        // Assert
        published.ShouldBe(1);
        (await RowsAsync(session, "SELECT * FROM copy", timeout.Token)).Count.ShouldBe(65);
        database.Catalog.GetPendingTableReclamations().ShouldBeEmpty();
        database.Coordinator.GetOpenContexts().ShouldBeEmpty();
    }

    private static async Task SeedAsync(SqlDatabaseSession session, CancellationToken cancellationToken)
    {
        await ExecAsync(session, "CREATE TABLE src (id INT PRIMARY KEY)", cancellationToken);
        await ExecAsync(session, "INSERT INTO src VALUES " + string.Join(',', Enumerable.Range(1, 65).Select(id => $"({id})")), cancellationToken);
    }

    private static async Task ExecAsync(SqlDatabaseSession session, string sql, CancellationToken cancellationToken)
        => (await session.ExecuteAsync(sql, cancellationToken: cancellationToken)).Status.ShouldBe(DatabaseResultStatus.Success);

    private static async Task<List<object?[]>> RowsAsync(SqlDatabaseSession session, string sql, CancellationToken cancellationToken)
    {
        await using var result = (DatabaseResultSet)await session.ExecuteAsync(sql, cancellationToken: cancellationToken);
        var rows = new List<object?[]>();
        await foreach (var row in result.GetRowsAsync(cancellationToken))
        { rows.Add(Enumerable.Range(0, row.FieldCount).Select(row.GetValue).ToArray()); }
        return rows;
    }

    private static async Task ReclaimAsync(SqlDatabase database, CancellationToken cancellationToken)
    {
        do
        {
            database.TableReclamation.RunBatch(cancellationToken);
            if (database.TableReclamation.HasWork) { await Task.Delay(1, cancellationToken); }
        } while (database.TableReclamation.HasWork);
    }
