    [Theory(DisplayName = "Cohesion Test [SqlEngine] - Identity: INSERT VALUES, SELECT and DEFAULT allocate each row")]
    [InlineData(10, 3)][InlineData(-10, -3)]
    public async Task ExecuteAsync_IdentitySources_ShouldHonorStartAndIncrement(long start, long increment)
    {
        // Arrange
        await using var engine = SqlDatabaseEngine.Create("identity", new SqlDatabaseEngineOptions());
        var database = await engine.CreateDatabaseAsync("ids", CancellationToken.None);
        await using var session = await database.CreateSessionAsync(CancellationToken.None);
        await ExecAsync(session, $"CREATE TABLE ids (id BIGINT GENERATED BY DEFAULT AS IDENTITY (START {start} INCREMENT {increment}) PRIMARY KEY, label INT)");

        // Act
        await ExecAsync(session, "INSERT INTO ids (label) VALUES (1), (2)");
        await ExecAsync(session, "INSERT INTO ids (label) SELECT label + 2 FROM ids");
        await ExecAsync(session, "INSERT INTO ids VALUES (DEFAULT, 5)");
        await ExecAsync(session, "INSERT INTO ids DEFAULT VALUES");
        await ExecAsync(session, "UPDATE ids SET id = DEFAULT WHERE label = 1");

        // Assert
        (await IdsAsync(session)).Order().ShouldBe(Enumerable.Range(1, 6).Select(index => start + index * increment).Order());
        var metadata = await RowsAsync(session, "SELECT COLUMN_DEFAULT, IS_NULLABLE, IS_IDENTITY, IDENTITY_GENERATION, IDENTITY_START, IDENTITY_INCREMENT, IDENTITY_MAXIMUM, IDENTITY_MINIMUM, IDENTITY_CYCLE FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'ids' AND COLUMN_NAME = 'id'");
        metadata.ShouldHaveSingleItem().ShouldBe(new object?[] { null, "NO", "YES", "BY DEFAULT", start.ToString(), increment.ToString(), long.MaxValue.ToString(), long.MinValue.ToString(), "NO" });
    }

    [Theory(DisplayName = "Cohesion Test [SqlEngine] - Identity: ALWAYS rejects explicit inserts and every update")]
    [InlineData("GENERATED ALWAYS AS IDENTITY")][InlineData("IDENTITY(1,1)")]
    public async Task ExecuteAsync_AlwaysIdentity_ShouldRejectExplicitAssignments(string clause)
    {
        // Arrange
        await using var engine = SqlDatabaseEngine.Create("identity", new SqlDatabaseEngineOptions());
        var database = await engine.CreateDatabaseAsync("ids", CancellationToken.None);
        await using var session = await database.CreateSessionAsync(CancellationToken.None);
        await ExecAsync(session, $"CREATE TABLE ids (id INT {clause} PRIMARY KEY)");
        await ExecAsync(session, "INSERT INTO ids DEFAULT VALUES");

        // Act / Assert
        foreach (string sql in new[] { "INSERT INTO ids VALUES (8)", "INSERT INTO ids VALUES (NULL)", "UPDATE ids SET id = 9", "UPDATE ids SET id = DEFAULT", "INSERT INTO ids (id) SELECT id FROM ids WHERE 1 = 0" })
        {
            var failure = await Should.ThrowAsync<DatabaseException>(() => ExecAsync(session, sql));
            failure.Message.ShouldContain("id", Case.Sensitive);
            failure.Diagnostics.ShouldHaveSingleItem().Code.ShouldBe("COHSQLE025");
        }
        (await IdsAsync(session)).ShouldBe([1L]);
    }

    [Fact(DisplayName = "Cohesion Test [SqlEngine] - Identity: BY DEFAULT explicit values leave the counter unchanged")]
