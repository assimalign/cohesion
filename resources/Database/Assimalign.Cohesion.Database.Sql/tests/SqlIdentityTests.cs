    [Theory(DisplayName = "Cohesion Test [SqlEngine] - Identity: durable reservations survive clean restart and crash")]
    [InlineData(false, 1)][InlineData(true, 1)][InlineData(true, -1)]
    public async Task OpenDatabaseAsync_IdentityReservation_ShouldNeverReuseValues(bool crash, int increment)
    {
        // Arrange
        var storage = new CrashCaptureSqlStorageStrategy();
        var engine = SqlDatabaseEngine.Create("identity", new SqlDatabaseEngineOptions { StorageStrategy = storage });
        try
        {
            var database = await engine.CreateDatabaseAsync("ids", CancellationToken.None);
            await using var session = await database.CreateSessionAsync(CancellationToken.None);
            long start = 10L * increment;
            await ExecAsync(session, $"CREATE TABLE ids (id BIGINT IDENTITY({start},{increment}))");
            for (int i = 0; i < 35; i++) { await ExecAsync(session, "INSERT INTO ids DEFAULT VALUES"); }
            long last = start + 34 * increment;
            var image = crash ? storage.CaptureDurableImages() : null;
            await session.DisposeAsync();
            await engine.DisposeAsync();

            // Act
            await using var reopened = SqlDatabaseEngine.Create("identity-reopen", new SqlDatabaseEngineOptions { StorageStrategy = image ?? storage.CaptureDurableImages() });
            var restored = await reopened.OpenDatabaseAsync("ids", CancellationToken.None);
            await using var next = await restored.CreateSessionAsync(CancellationToken.None);
            await ExecAsync(next, "INSERT INTO ids DEFAULT VALUES");

            // Assert
            var ids = await IdsAsync(next);
            (increment > 0 ? ids.Max() > last : ids.Min() < last).ShouldBeTrue();
            ids.Distinct().Count().ShouldBe(ids.Length);
            ids.ShouldContain(start + 64 * increment);
        }
        finally { await engine.DisposeAsync(); }
    }

    [Fact(DisplayName = "Cohesion Test [SqlEngine] - Identity: concurrent explicit and implicit transactions allocate distinct values")]
    public async Task ExecuteAsync_ConcurrentSessions_ShouldAllocateDistinctValues()
    {
        // Arrange
        using var timeout = new CancellationTokenSource(TimeSpan.FromSeconds(30));
        await using var engine = SqlDatabaseEngine.Create("identity", new SqlDatabaseEngineOptions());
        var database = await engine.CreateDatabaseAsync("ids", timeout.Token);
        await using var setup = await database.CreateSessionAsync(timeout.Token);
        await ExecAsync(setup, "CREATE TABLE ids (id BIGINT IDENTITY PRIMARY KEY)");
        int inserts = 0, transactions = 0;
        var elapsed = Stopwatch.StartNew();

        // Act: require a minimum duration AND observed work, with a cancellation ceiling.
        await Task.WhenAll(Enumerable.Range(0, 6).Select(async worker =>
        {
            await using var session = await database.CreateSessionAsync(timeout.Token);
            do
            {
                timeout.Token.ThrowIfCancellationRequested();
                bool explicitTransaction = worker % 2 == 0;
                if (explicitTransaction) { await session.ExecuteAsync("BEGIN", cancellationToken: timeout.Token); }
                await session.ExecuteAsync("INSERT INTO ids DEFAULT VALUES", cancellationToken: timeout.Token);
                if (explicitTransaction)
                {
                    await Task.Yield();
                    await session.ExecuteAsync("COMMIT", cancellationToken: timeout.Token);
                    Interlocked.Increment(ref transactions);
                }
                Interlocked.Increment(ref inserts);
            }
            while (elapsed.Elapsed < TimeSpan.FromMilliseconds(150) || Volatile.Read(ref inserts) < 96 || Volatile.Read(ref transactions) < 12);
        }));

        // Assert
        inserts.ShouldBeGreaterThanOrEqualTo(96);
        transactions.ShouldBeGreaterThanOrEqualTo(12);
        var ids = await IdsAsync(setup);
        ids.Length.ShouldBe(inserts);
        ids.Distinct().Count().ShouldBe(inserts);
    }

