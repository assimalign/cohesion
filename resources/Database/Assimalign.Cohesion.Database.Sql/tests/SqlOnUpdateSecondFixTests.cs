    public static IEnumerable<object[]> StorageCases()
    {
        for (int replacement = 0; replacement < 5; replacement++)
        { for (int path = 0; path < 5; path++)
          { foreach (string action in new[] { "CASCADE", "SET NULL", "SET DEFAULT" }) { yield return [replacement, path, action]; } } }
    }

    [Theory(DisplayName = "Cohesion Test [Sql] - Storage replacement: every DML path retains referential actions, charges and sequence admission (#1723)")]
    [MemberData(nameof(StorageCases))]
    public async Task ExecuteAsync_StorageReplacement_ShouldRetainActionEligibility(int replacement, int path, string action)
    {
        // Arrange: any DML primes the catalog directory before storage owners change.
        await using var engine = SqlDatabaseEngine.Create("replacement-actions", new());
        var db = await engine.CreateDatabaseAsync("db");
        await using var session = await db.CreateSessionAsync();
        await session.ExecuteAsync("CREATE SEQUENCE s AS INT START WITH 10");
        await session.ExecuteAsync("CREATE TABLE p(tag INT PRIMARY KEY,k INT UNIQUE,extra INT)");
        await session.ExecuteAsync($"CREATE TABLE c(id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,k INT DEFAULT NEXT VALUE FOR s REFERENCES p(k) ON UPDATE {action} ON DELETE {action})");
        await session.ExecuteAsync("DELETE FROM c");
        db.Catalog.TryGetTable("dbo", "p", out var before).ShouldBeTrue();
        switch (replacement)
        {
            case 0: await session.ExecuteAsync("TRUNCATE p,c"); break;
            case 1: await db.RewriteTableAsync("dbo", "p", CancellationToken.None); break;
            case 2: await db.RewriteTableAsync("dbo", "c", CancellationToken.None); break;
            case 3: await session.ExecuteAsync("TRUNCATE p,c RESTART IDENTITY"); break;
            default: await session.ExecuteAsync("ALTER TABLE p ALTER COLUMN extra TYPE BIGINT"); break;
        }
        db.Catalog.TryGetTable("dbo", "p", out var parent).ShouldBeTrue();
        if (replacement != 2) { parent.ObjectId.ShouldNotBe(before.ObjectId); }
        await session.ExecuteAsync("INSERT INTO p VALUES(1,1,0),(10,10,0)");
        await session.ExecuteAsync("INSERT INTO c VALUES(1,1)");
        string sql = path == 4 ? "DELETE FROM p WHERE tag=1" : SqlOnUpdateClosureTests.UpdateKey(path, "2");
        int plans = 0;
        SqlQueryExecutor.AfterPlan = (_, plan) =>
        {
            plans++;
            if (action == "SET DEFAULT") { plan.SequenceUsage.ShouldNotBeNull(); }
        };

        // Act
        try { (await session.ExecuteAsync(sql)).AffectedCount.ShouldBe(1); }
        finally { SqlQueryExecutor.AfterPlan = null; }
        var metrics = session.LastStatementMetrics.ShouldNotBeNull();

        // Assert
        plans.ShouldBe(1);
        metrics.PeakHashMemoryBytes.ShouldBeGreaterThan(0);
        metrics.HashMemoryBytes.ShouldBe(0);
        object?[][] expected = action == "CASCADE" ? path == 4 ? [] : [[2]] : action == "SET NULL" ? [[null]] : [[10]];
        (await SqlOnUpdateClosureTests.Rows(session, "SELECT k FROM c")).ShouldBe(expected);
        if (action == "SET DEFAULT") { (await SqlOnUpdateClosureTests.Rows(session, "SELECT lastval()")).ShouldBe([[10L]]); }
    }

    public static IEnumerable<object[]> SharedCellCases()
    {
        foreach (var tables in Permute(["g", "p", "q", "c"]))
        { for (int physical = 0; physical < 3; physical++) { yield return [string.Join(',', tables), physical]; } }
    }

    [Theory(DisplayName = "Cohesion Test [Sql] - Shared cells: all table and constraint orders converge for one row and both two-row orders (#1723)")]
    [MemberData(nameof(SharedCellCases))]
    public async Task ExecuteAsync_SharedCellOrigins_ShouldCompareCompletedProposals(string tableOrder, int physical)
    {
        foreach (var constraints in Permute(["pa", "qi", "pb", "cxy", "cy"]))
        {
            // Arrange: 24 table orders x 120 constraint orders x 3 physical variants.
            await using var engine = SqlDatabaseEngine.Create("shared-action-cell", new());
            var db = await engine.CreateDatabaseAsync("db");
            await using var session = await db.CreateSessionAsync();
            var declarations = new Dictionary<string, string>
            {
                ["g"] = "id INT PRIMARY KEY", ["p"] = "a INT,b INT,PRIMARY KEY(a,b)",
                ["q"] = "id INT PRIMARY KEY", ["c"] = "x INT,y INT",
            };
            foreach (string table in tableOrder.Split(',')) { await session.ExecuteAsync($"CREATE TABLE {table}({declarations[table]})"); }
            var edges = new Dictionary<string, string>
            {
                ["pa"] = "p ADD FOREIGN KEY(a) REFERENCES g(id)", ["qi"] = "q ADD FOREIGN KEY(id) REFERENCES g(id)",
                ["pb"] = "p ADD FOREIGN KEY(b) REFERENCES q(id)", ["cxy"] = "c ADD FOREIGN KEY(x,y) REFERENCES p(a,b)",
                ["cy"] = "c ADD FOREIGN KEY(y) REFERENCES q(id)",
            };
            foreach (string edge in constraints) { await session.ExecuteAsync($"ALTER TABLE {edges[edge]} ON UPDATE CASCADE"); }
            string[] rows = physical == 0 ? ["1"] : physical == 1 ? ["1", "2"] : ["2", "1"];
            foreach (string table in new[] { "g", "q", "p", "c" })
            { await session.ExecuteAsync($"INSERT INTO {table} VALUES" + string.Join(',', rows.Select(i => table is "p" or "c" ? $"({i},{i})" : $"({i})"))); }

            // Act
            await session.ExecuteAsync("UPDATE g SET id=id+100");

            // Assert
            (await SqlOnUpdateClosureTests.Rows(session, "SELECT x,y FROM c ORDER BY x"))
                .ShouldBe(physical == 0 ? [[101,101]] : [[101,101],[102,102]], $"tables={tableOrder}; constraints={string.Join(',', constraints)}; physical={physical}");
            session.LastStatementMetrics.ShouldNotBeNull().HashMemoryBytes.ShouldBe(0);
        }
    }

    [Theory(DisplayName = "Cohesion Test [Sql] - DELETE SET and UPDATE actions: different replacements conflict and equal replacements converge (#1723)")]
    [InlineData(false)][InlineData(true)]
    public async Task ExecuteAsync_DeleteSetAndUpdateAction_ShouldCompareBothOrigins(bool equal)
    {
        // Arrange
        await using var engine = SqlDatabaseEngine.Create("delete-update-proposals", new());
        var db = await engine.CreateDatabaseAsync("db");
        await using var session = await db.CreateSessionAsync();
        await session.ExecuteAsync("CREATE TABLE p(id INT PRIMARY KEY)");
        await session.ExecuteAsync("INSERT INTO p VALUES(0),(1)");
        await session.ExecuteAsync("CREATE TABLE q(k INT PRIMARY KEY DEFAULT 0 REFERENCES p(id) ON DELETE SET DEFAULT)");
        await session.ExecuteAsync("INSERT INTO q VALUES(1)");
        await session.ExecuteAsync("CREATE TABLE c(x INT DEFAULT 0 REFERENCES q(k) ON UPDATE CASCADE,FOREIGN KEY(x) REFERENCES p(id) ON DELETE " + (equal ? "SET DEFAULT" : "SET NULL") + ")");
        await session.ExecuteAsync("INSERT INTO c VALUES(1)");

        // Act
        if (equal) { (await session.ExecuteAsync("DELETE FROM p WHERE id=1")).AffectedCount.ShouldBe(1); }
        else
        {
            var error = await Should.ThrowAsync<DatabaseException>(async () => await session.ExecuteAsync("DELETE FROM p WHERE id=1"));
            error.Diagnostics.ShouldContain(d => d.Code == "CS05085");
        }

        // Assert
        session.LastStatementMetrics.ShouldNotBeNull().HashMemoryBytes.ShouldBe(0);
        (await SqlOnUpdateClosureTests.Rows(session, "SELECT x FROM c")).ShouldBe(equal ? [[0]] : [[1]]);
        (await SqlOnUpdateClosureTests.Rows(session, "SELECT k FROM q")).ShouldBe(equal ? [[0]] : [[1]]);
        (await SqlOnUpdateClosureTests.Rows(session, "SELECT id FROM p ORDER BY id")).ShouldBe(equal ? [[0]] : [[0],[1]]);
    }

    [Fact(DisplayName = "Cohesion Test [Sql] - MERGE DELETE SET and direct UPDATE: both origins participate before action matching (#1723)")]
    public async Task ExecuteAsync_MergeDeleteSetAndDirectUpdate_ShouldRefuseConflictingOrigins()
    {
        // Arrange
        await using var engine = SqlDatabaseEngine.Create("merge-delete-update-proposals", new());
        var db = await engine.CreateDatabaseAsync("db");
        await using var session = await db.CreateSessionAsync();
        await session.ExecuteAsync("CREATE TABLE p(tag INT PRIMARY KEY,a INT UNIQUE,b INT UNIQUE)");
        await session.ExecuteAsync("INSERT INTO p VALUES(1,1,10),(2,2,1)");
        await session.ExecuteAsync("CREATE TABLE c(x INT REFERENCES p(a) ON DELETE SET NULL,FOREIGN KEY(x) REFERENCES p(b) ON UPDATE CASCADE)");
        await session.ExecuteAsync("INSERT INTO c VALUES(1)");

        // Act
        var error = await Should.ThrowAsync<DatabaseException>(async () => await session.ExecuteAsync(
            "MERGE INTO p USING (SELECT 1 AS tag UNION ALL SELECT 2) s ON p.tag=s.tag " +
            "WHEN MATCHED AND p.tag=1 THEN DELETE WHEN MATCHED THEN UPDATE SET b=2"));

        // Assert
        error.Diagnostics.ShouldContain(d => d.Code == "CS05085");
        session.LastStatementMetrics.ShouldNotBeNull().HashMemoryBytes.ShouldBe(0);
        (await SqlOnUpdateClosureTests.Rows(session, "SELECT x FROM c")).ShouldBe([[1]]);
        (await SqlOnUpdateClosureTests.Rows(session, "SELECT tag,a,b FROM p ORDER BY tag")).ShouldBe([[1,1,10],[2,2,1]]);
    }

    [Fact(DisplayName = "Cohesion Test [Sql] - DELETE cascade budget: all operational references state the two-column charge and default cap (#1723)")]
