        }
    }

    private static string ProjectDirectory([CallerFilePath] string source = "") => Path.Combine(Path.GetDirectoryName(source)!, "..");

    private static IEnumerable<string[]> Permute(string[] values)
    {
        if (values.Length == 0) { yield return []; }
        foreach (string value in values)
        { foreach (var tail in Permute(values.Where(v => v != value).ToArray())) { yield return [value, .. tail]; } }
    }
