using System;
using System.Threading;
using System.Threading.Tasks;

using Shouldly;
using Xunit;

using Assimalign.Cohesion.Database.Sql.Internal;
using Assimalign.Cohesion.Database.Sql.Language;

namespace Assimalign.Cohesion.Database.Sql.Tests;

public sealed partial class SqlIdentityReviewTests
{
    [Theory(DisplayName = "Cohesion Test [Sql] - DELETE: a new SET DEFAULT sequence dependency requires replanning")]
    [InlineData(false)][InlineData(true)]
    public async Task ExecuteAsync_ReferentialActionChangedAfterPlan_ShouldRetryBeforeAllocation(bool identity)
    {
        // Arrange
        await using var engine = SqlDatabaseEngine.Create("fk-action-plan-review", new());
        var db = await engine.CreateDatabaseAsync("db", CancellationToken.None);
        await using var session = await db.CreateSessionAsync(CancellationToken.None);
        await using var ddl = await db.CreateSessionAsync(CancellationToken.None);
        await Exec(ddl, "CREATE SEQUENCE s START 2");
        await Exec(ddl, "CREATE TABLE p(id BIGINT PRIMARY KEY)");
        await Exec(ddl, "INSERT INTO p VALUES(1),(2)");
        await Exec(ddl, "CREATE TABLE c(pid BIGINT " + (identity ? "GENERATED BY DEFAULT AS IDENTITY" : "DEFAULT nextval('s')") +
            ", CONSTRAINT fk FOREIGN KEY(pid) REFERENCES p(id) ON DELETE SET NULL)");
        await Exec(ddl, identity ? "INSERT INTO c DEFAULT VALUES" : "INSERT INTO c VALUES(1)");
        int plans = 0;
        int allocations = 0;
        db.Catalog.AllocationEntering = () => allocations++;
        SqlQueryExecutor.AfterPlan = (request, plan) =>
        {
            if (request.Statement.SqlExpression is not SqlDeleteExpression) { return; }
            plans++;
            plan.SequenceUsage.ShouldBeNull();
            SqlQueryExecutor.AfterPlan = null;
            Exec(ddl, "ALTER TABLE c DROP CONSTRAINT fk").GetAwaiter().GetResult();
            Exec(ddl, "ALTER TABLE c ADD CONSTRAINT fk FOREIGN KEY(pid) REFERENCES p(id) ON DELETE SET DEFAULT").GetAwaiter().GetResult();
        };
        try
        {
            // Act
            var failure = await Should.ThrowAsync<DatabaseException>(() => Exec(session, "DELETE FROM p WHERE id=1"));

            // Assert: the failed statement changed neither table nor sequence state; a fresh plan succeeds.
            plans.ShouldBe(1);
            failure.Diagnostics[0].Code.ShouldBe("CS04067");
            allocations.ShouldBe(0);
            (await Rows(session, "SELECT COUNT(*) FROM p"))[0][0].ShouldBe(2L);
            (await Rows(session, "SELECT pid FROM c"))[0][0].ShouldBe(1L);
            await Exec(session, "DELETE FROM p WHERE id=1");
            allocations.ShouldBe(1);
            (await Rows(session, "SELECT id FROM p"))[0][0].ShouldBe(2L);
            (await Rows(session, "SELECT pid FROM c"))[0][0].ShouldBe(2L);
        }
        finally { SqlQueryExecutor.AfterPlan = null; db.Catalog.AllocationEntering = null; }
    }
}
