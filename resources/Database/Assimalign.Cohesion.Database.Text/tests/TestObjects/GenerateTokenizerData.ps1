# Freeze the .NET 10 managed letter/decimal-digit classification, independent of
# the runtime/globalization tables on the machine eventually reading an index.
$ErrorActionPreference = 'Stop'
if ([Environment]::Version.Major -ne 10) { throw 'Generate with a .NET 10 PowerShell host.' }
$ranges = [Collections.Generic.List[int]]::new()
$start = -1
for ($scalar = 0; $scalar -le 0x10ffff; $scalar++) {
    $included = ($scalar -lt 0xd800 -or $scalar -gt 0xdfff) -and [Text.Rune]::IsLetterOrDigit([Text.Rune]::new($scalar))
    if ($included -and $start -lt 0) { $start = $scalar }
    if (!$included -and $start -ge 0) { $ranges.Add($start); $ranges.Add($scalar - 1); $start = -1 }
}
if ($start -ge 0) { $ranges.Add($start); $ranges.Add(0x10ffff) }
$rows = for ($i = 0; $i -lt $ranges.Count; $i += 2) { '        0x{0:X}, 0x{1:X},' -f $ranges[$i],$ranges[$i+1] }
$source = @'
// <auto-generated />
// Pinned .NET 10 managed Unicode letter and decimal-digit ranges.
// Reproduce with tests/TestObjects/GenerateTokenizerData.ps1. Changes require an
// analyzer version bump; no OS, ICU or consuming runtime category calls are used.
using System;

namespace Assimalign.Cohesion.Database.Text.Internal;

internal static class TextUnicodeData
{
    private static readonly int[] _ranges =
    [
'@ + "`n" + ($rows -join "`n") + @'

    ];

    internal static bool IsLetterOrDigit(int scalar)
    {
        ReadOnlySpan<int> ranges = _ranges;
        int low = 0, high = ranges.Length / 2 - 1;
        while (low <= high)
        {
            int middle = (low + high) / 2;
            if (scalar < ranges[middle * 2])
            {
                high = middle - 1;
            }
            else if (scalar > ranges[middle * 2 + 1])
            {
                low = middle + 1;
            }
            else
            {
                return true;
            }
        }

        return false;
    }
}
'@
$path = [IO.Path]::GetFullPath("$PSScriptRoot/../../src/Internal/TextUnicodeData.Generated.cs")
[IO.File]::WriteAllText($path,($source -replace '\r?\n',"`r`n"),[Text.UTF8Encoding]::new($false))
Write-Output "Generated $($ranges.Count / 2) letter/digit ranges."
